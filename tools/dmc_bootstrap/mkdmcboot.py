# open-simh-extended/tools/dmc_bootstrap/mkdmcboot.py  v3 (v3: location counter modification (.BLKW between data) accepted; v2: internal displaced relocation applied: PC-relative words were left as the label value)
#
# Turns the object file of PDP11/pdp11_dmc_boot.mac (the DMC11/DMR11 MOP
# bootstrap of SIMH's BOOT DMCn, assembled with the macro11 cross
# assembler, one absolute section from address 0) into the C header
# PDP11/pdp11_dmc_boot.h: the words from 0 up to CODLEN = RBUF (the code,
# its stack, base table and transmit buffer; the receive buffer behind it is
# not copied) and the offsets SIMH needs.
#
# The object file is RT-11 formatted binary: records "1, 0, length, data,
# checksum"; the data start with a record type (1 GSD, 2 end of GSD, 3 TXT,
# 4 RLD, 5 ISD, 6 end of module).  A TXT record holds a load address and
# the bytes from there.  Relocation (RLD) other than location counter
# definitions and modifications (.BLKW) of the absolute section and internal
# displaced relocation is refused (an undefined symbol shows up as a global
# reference), because the program must be position independent.  Internal
# displaced relocation is a PC-relative reference to a label of the section:
# its TXT word holds the label's value, and the word stored is value -
# (location + 2), which stays right wherever the program is copied.
#
# usage (macro11: github.com/shattered/macro11 v0.3, see known issue 96):
#   macro11 -o dmcboot.obj -l dmcboot.lst PDP11/pdp11_dmc_boot.mac
#   python3 -I mkdmcboot.py dmcboot.obj dmcboot.lst PDP11/pdp11_dmc_boot.h
# The listing must show no errors (macro11 v0.3 wrongly rejects JMP (R0),
# so the program jumps through R2).
import sys, re

def records(data):
    """Yield the bodies of the formatted binary records."""
    i = 0
    while i < len(data):
        if data[i] == 0:                        # fill between records
            i += 1
            continue
        if data[i] != 1 or data[i + 1] != 0:
            raise SystemExit("bad record lead at %d" % i)
        n = data[i + 2] | (data[i + 3] << 8)
        if (sum(data[i:i + n + 1]) & 0xFF) != 0:
            raise SystemExit("checksum error at %d" % i)
        yield data[i + 4:i + n]
        i += n + 1

def symbols(lst):
    """Label and symbol values from the listing's symbol table (octal)."""
    sym = {}
    for name in ("CSR", "DEVT", "PROGT", "TICKS", "CODLEN", "RBEND"):
        m = re.search(r"^\s*\d+\s+([0-7]{6})\s+(?:[0-7]{3,6}'?\s+)*%s:" % name, lst, re.M) or \
            re.search(r"^\s*\d+\s+([0-7]{6})\s+%s\s*=" % name, lst, re.M)
        if not m:
            raise SystemExit("symbol %s not found in the listing" % name)
        sym[name] = int(m.group(1), 8)
    return sym

def main():
    obj, lstname, out = sys.argv[1:4]
    mem = {}
    txt = None                                          # load address of the last TXT record
    for body in records(open(obj, 'rb').read()):
        rtype = body[0] | (body[1] << 8)
        if rtype == 3:                                  # TXT
            txt = body[2] | (body[3] << 8)
            for k, b in enumerate(body[4:]):
                mem[txt + k] = b
        elif rtype == 4:                                # RLD
            j = 2
            while j < len(body):
                cmd = body[j] & 0x7F
                if cmd == 7:                            # location counter definition:
                    j += 2 + 4 + 2                      #   command, displ., name, value
                elif cmd == 0o10:                       # location counter modification
                    j += 2 + 2                          #   (.BLKW): TXT has its address
                elif cmd == 3:                          # internal displaced: a PC-relative
                    # reference to a label of the section; the TXT word holds the
                    # label's value, the word to store is value - (location + 2).
                    # The displacement counts from the TXT record's address word.
                    loc = txt + body[j + 1] - 4
                    val = body[j + 2] | (body[j + 3] << 8)
                    w = (val - (loc + 2)) & 0xFFFF
                    mem[loc], mem[loc + 1] = w & 0xFF, w >> 8
                    j += 2 + 2
                else:
                    raise SystemExit("relocation type %o: the program must be position independent" % cmd)
    lst = open(lstname).read()
    if "ERROR" in lst:
        raise SystemExit("the listing has errors")
    sym = symbols(lst)
    end = sym["CODLEN"]
    words = []
    for a in range(0, end, 2):
        words.append(mem.get(a, 0) | (mem.get(a + 1, 0) << 8))
    with open(out, 'w', newline='\r\n') as f:
        f.write("/* pdp11_dmc_boot.h: DMC11/DMR11 MOP bootstrap for BOOT DMCn\n\n")
        f.write("   Generated by tools/dmc_bootstrap/mkdmcboot.py (notes branch) from\n")
        f.write("   pdp11_dmc_boot.mac, assembled with the macro11 cross assembler.\n")
        f.write("   Do not edit: change pdp11_dmc_boot.mac and generate it again.\n\n")
        f.write("   The program is position independent.  SIMH copies the words below\n")
        f.write("   to the top of the low 56 KB of memory (DMCB_AREA bytes are used,\n")
        f.write("   the receive buffer behind the copied words included), fills in\n")
        f.write("   the parameters and starts it at its first word. */\n\n")
        f.write("#define DMCB_AREA   0%o     /* bytes of memory the bootstrap uses */\n" % sym["RBEND"])
        f.write("#define DMCB_CSR    0%o        /* parameter: the board's CSR (word) */\n" % sym["CSR"])
        f.write("#define DMCB_DEVT   0%o        /* parameter: MOP device type (byte) */\n" % sym["DEVT"])
        f.write("#define DMCB_PROGT  0%o        /* parameter: MOP program type (byte) */\n" % sym["PROGT"])
        f.write("#define DMCB_TICKS  0%o        /* parameter: wait loops of about 5 s (word) */\n" % sym["TICKS"])
        f.write("#define DMCB_LOOP   30000      /* instructions in one wait loop (10000 polls) */\n\n")
        f.write("static const uint16 dmc_boot_code[] = {\n")
        for k in range(0, len(words), 8):
            f.write("    " + ", ".join("0%06o" % w for w in words[k:k + 8]) + ",\n")
        f.write("    };\n")
    print("%s: %d words (code up to %06o), area %06o bytes" % (out, len(words), end, sym["RBEND"]))

main()
