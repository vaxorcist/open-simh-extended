# open-simh-extended/tests/ra/ratest.py  v2
#
# v2 (2026-11-10): RA81 spin-up now 20 s (User Guide).
#
# Tests of the fixed RA drives in the sound realism mode of the RQ device
# (RUN/STOP button, realistic seek/rotation/transfer timing, seek sounds;
# sound patch v23, 2026-11-10) with VMS V4.7 (Ulli's image VMS047-1.R81,
# RA81, VHD; SYSTEM/MANAGER):
#
#   N1 normal mode, MicroVAX II (KDA50), RA81 system disk: boot, log in,
#        the timed workload (DIRECTORY/SIZE, COPY, DELETE).  Regression and
#        reference times: nothing may change without SET SOUND ENABLED.
#   R1 realism mode, MicroVAX II (KDA50, THROTTLE 450K by default):
#        - ATTACH leaves the RA81 stopped; SET RQ0 ONLINE waits for the
#          spin-up (SPINUPRA81, 20 s); boot, log in, the timed workload;
#        - a blank RA92 data disk: SET -N RQ1 ONLINE (spins up while VMS
#          runs), INITIALIZE, MOUNT, COPY, DIRECTORY, DISMOUNT (VMS unloads:
#          the drive spins down, the file stays attached);
#        - MOUNT of the stopped RA92: VMS asks the operator to mount it;
#          SET -N RQ1 ONLINE: the volume mounts by itself when the drive is
#          up to speed;
#        - RUN/STOP of the system disk under the running system: SET -N RQ0
#          OFFLINE, a DCL command: mount verification; SET -N RQ0 ONLINE:
#          mount verification completes, the command too.
#   U1 realism mode, VAX-11/750 (UDA50A, THROTTLE 300K): the same system on
#        an RA82 (flat copy of the image, NOAUTOSIZE): ONLINE, boot, log in,
#        the timed workload.
#   T1 realism mode, MicroVAX II (KDA50): the same system on an RA72, then
#        on an RA71 (flat copy, NOAUTOSIZE): boot, the timed workload.
#        (VMS V4.7 cannot mount its system disk on an RA90 or RA92, also
#        in the normal mode of unmodified SIMH: "%SYSINIT-E- error mounting
#        system device, status = 000008C4"; the RA92 is tested as a data
#        disk in R1.)
#
# Usage: python3 -I ratest.py <BIN directory> <VMS047-1.R81> <work dir> [N1|R1|U1|T1 ...]
# The image is copied (VHD for N1/R1, flat copies for U1/T1 made with
# vhd2raw.py from the same directory); the original is not changed.  The
# simulator output goes to <work dir>/<test>.log, the RQ trace (seek
# sounds, transfer times) to <work dir>/<test>.trc.
import sys, os, subprocess, shutil, time, re

def step(cmd, tag):
    """DCL command, then a marker line; the script stops at the marker."""
    return ('send after=500000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"\n'
            'expect "=%sEND="\ncontinue\n' % (cmd.replace('"', '\\"'), tag, tag))

def clock(tag):
    return step('WRITE SYS$OUTPUT "CLOCK ' + tag + ' ",F$TIME()', "K" + tag)

LOGIN = ('expect "job terminated" send after=2000000,"\\r"; continue\n'
         'expect "Username:" send "SYSTEM\\r"; continue\n'
         'expect "Password:" send "MANAGER\\r"; continue\n'
         'expect "Welcome"\n')

MVBOOT = ('expect ">>>" send "B DUA0\\r"; continue\n'
          'expect "HH:MM)" send "10-NOV-2026 12:00\\r"; continue\n')

def workload(t):
    """The timed workload on the system disk"""
    s = clock(t + "1")
    s += step("DIRECTORY/SIZE/TOTAL SYS$SYSTEM:", t + "A")
    s += step("COPY SYS$HELP:*.HLB SYS$LOGIN:", t + "B")
    s += step("DIRECTORY/SIZE/TOTAL SYS$LOGIN:*.HLB", t + "C")
    s += step("DELETE SYS$LOGIN:*.HLB;*", t + "D")
    s += clock(t + "2")
    return s

def run(sim, ini, log, limit):
    t = time.time()
    env = dict(os.environ)
    env["SDL_AUDIODRIVER"] = "dummy"
    with open(log, "wb") as f:
        subprocess.run([sim, ini], stdout=f, stderr=subprocess.STDOUT, timeout=limit,
                       env=env, stdin=subprocess.DEVNULL)
    txt = open(log, "rb").read().replace(b"\0", b"").decode("latin-1")
    return txt, time.time() - t

def flat(image, path):
    here = os.path.dirname(os.path.abspath(__file__))
    subprocess.run([sys.executable, "-I", os.path.join(here, "vhd2raw.py"), image, path], check=True)

def main():
    bindir, image, work = sys.argv[1], sys.argv[2], sys.argv[3]
    which = sys.argv[4:] or ["N1", "R1", "U1", "T1"]
    os.makedirs(work, exist_ok=True)
    w = lambda f: os.path.join(work, f)
    res = []
    for test in which:
        t = test[0]
        trc = w(test.lower() + ".trc")
        s = "; %s (generated by ratest.py v2)\n" % test
        if test == "N1":
            sim = "microvax2"
            disk = w("n1.vhd"); shutil.copyfile(image, disk); os.chmod(disk, 0o644)
            s += "set cpu 16m\nset rq kda50\nset rq0 ra81\nattach rq0 %s\n" % disk
            s += "show rq0 spindle\nset runlimit 3600 seconds\n" + MVBOOT + LOGIN + "boot cpu\n"
            s += workload(t)
        elif test == "R1":
            sim = "microvax2"
            disk = w("r1.vhd"); shutil.copyfile(image, disk); os.chmod(disk, 0o644)
            data = w("r1_ra92.dsk")
            if os.path.exists(data):
                os.remove(data)
            s += "set sound enabled\nset cpu 16m\nset rq kda50\nset rq0 ra81\nset rq1 ra92\n"
            s += "attach rq0 %s\nattach -n rq1 %s\n" % (disk, data)
            s += "echo ==== R1: after ATTACH\nshow rq0 spindle\nshow rq1 spindle\n"
            s += "set rq0 online\necho ==== R1: after SET RQ0 ONLINE\nshow rq0 spindle\n"
            s += "set debug %s\nset rq debug=trace\n" % trc
            s += "set runlimit 7200 seconds\n" + MVBOOT + LOGIN + "boot cpu\n"
            s += "set -n rq1 online\necho ==== R1: SET -N RQ1 ONLINE under VMS\nshow rq1 spindle\n"
            s += workload(t)
            s += step("WAIT 00:00:45", t + "W")      # RA92 spin-up 40 s
            s += "show rq1 spindle\n"
            s += step("SHOW DEVICE DU", t + "E")
            s += step("INITIALIZE DUA1: RA92T", t + "F")
            s += step("MOUNT DUA1: RA92T", t + "G")
            s += step("COPY SYS$HELP:*.HLB DUA1:[000000]", t + "H")
            s += step("DIRECTORY/SIZE/TOTAL DUA1:[000000]", t + "I")
            s += step("DISMOUNT DUA1:", t + "J")
            s += "echo ==== R1: after DISMOUNT DUA1 (VMS unloads: spin-down)\nshow rq1 spindle\nshow rq1\n"
            s += step("WAIT 00:00:35", t + "V")      # RA92 spin-down 30 s
            s += "show rq1 spindle\n"
            # MOUNT of the stopped drive: operator request; then the RUN/STOP button
            s += ('send after=500000,"MOUNT DUA1: RA92T\\r"\n'
                  'expect "Please mount"\ncontinue\n')
            s += "echo ==== R1: MOUNT waits for the operator\nset -n rq1 online\n"
            s += ('send after=500000,"WRITE SYS$OUTPUT \\"=RM\\",\\"END=\\"\\r"\n'
                  'expect "=RMEND="\ncontinue\n')
            s += step("SHOW DEVICE DUA1:", t + "K")
            s += step("DIRECTORY/SIZE/TOTAL DUA1:[000000]", t + "L")
            s += step("DISMOUNT/NOUNLOAD DUA1:", t + "M")
            s += "show rq1 spindle\n"
            # RUN/STOP of the system disk under the running system
            s += "set -n rq0 offline\necho ==== R1: SET -N RQ0 OFFLINE under VMS\n"
            s += ('send after=500000,"DIRECTORY/SIZE/TOTAL SYS$SYSTEM:*.EXE\\r"\n'
                  'expect "Mount verification in progress"\ncontinue\n')
            s += "echo ==== R1: mount verification, SET -N RQ0 ONLINE\nshow rq0 spindle\nset -n rq0 online\n"
            s += ('expect "completed mount verification"\ncontinue\n')
            s += step("SHOW DEVICE DUA0:", t + "N")
            s += "show rq0 spindle\n"
        elif test == "U1":
            sim = "vax750"
            disk = w("u1_ra82.raw"); flat(image, disk)
            s += "set sound enabled\nset cpu 8m\nset rq0 ra82\nset rq0 noautosize\nset rq0 format=raw\n"
            s += "attach rq0 %s\nshow rq0\nset rq0 online\n" % disk
            s += "set debug %s\nset rq debug=trace\n" % trc
            s += "set runlimit 7200 seconds\n" + LOGIN + "boot rq0\n"
            s += workload(t)
        elif test == "T1":
            sim = "microvax2"
            disk = w("t1.raw"); flat(image, disk)
            s += "set sound enabled\nset cpu 16m\nset rq kda50\n"
            for n, ty in ((0, "ra72"), (1, "ra71")):
                tg = "T" + str(n + 1)
                s += "set rq0 %s\nset rq0 noautosize\nset rq0 format=raw\n" % ty
                s += "attach rq0 %s\nset rq0 online\n" % disk
                s += "set debug %s\nset rq debug=trace\n" % (w("t1_%s.trc" % ty))
                s += "set runlimit 3600 seconds\n" + MVBOOT + LOGIN + "boot cpu\n"
                s += workload(tg)
                s += "set nodebug\nset rq0 offline\ndetach rq0\n"
        else:
            sys.exit("unknown test " + test)
        s += "exit\n"
        ini = w(test.lower() + ".ini")
        open(ini, "w").write(s)
        txt, secs = run(os.path.join(bindir, sim), ini, w(test.lower() + ".log"), 7500)
        res.append((test, secs, txt))
        print("%s: %.0f s wall" % (test, secs), flush=True)
    for test, secs, txt in res:
        print("==== %s" % test)
        for line in txt.splitlines():
            l = line.strip()
            if (l.startswith("CLOCK") or l.startswith("====") or "RQ" in l[:4] or
                "Total of" in l or "%MOUNT" in l or "%SYSTEM" in l or "spinning" in l or
                "up to speed" in l or "at rest" in l or l in ("online", "offline") or
                "mount verification" in l.lower() or "mount" in l.lower() and "please" in l.lower() or
                l.startswith("DUA") or "-F-" in l or "-E-" in l or "-W-" in l):
                print("   " + l)
    for f in sorted(os.listdir(work)):
        if f.endswith(".trc"):
            txt = open(w(f), errors="replace").read()
            snd = re.findall(r"seek sound (\w+)", txt)
            us = [int(x) for x in re.findall(r"cylinders \d+-\d+, (\d+) us", txt)]
            print("%s: %d transfers, longest %.1f ms, mean %.1f ms; seek sounds short %d, medium %d, long %d"
                  % (f, len(us), max(us or [0]) / 1000.0, (sum(us) / len(us) / 1000.0) if us else 0,
                     snd.count("short"), snd.count("medium"), snd.count("long")))

main()
