# open-simh-extended/tests/tk50/tktest.py  v1
#
# TK50 tests with VMS V4.7 (Ulli's image VMS047-1.R81, RA81, VHD;
# SYSTEM/MANAGER) for the sound realism mode of the TQ device (TK50 as a
# cartridge streamer, SND_STREAMER in sim_sound.c; 2026-11-08):
#
#   K1 normal mode, MicroVAX II (TQK50): ATTACH, INITIALIZE MUA0:, BACKUP
#        save set, BACKUP/LIST, DISMOUNT (unloads: detaches, as before).
#        Regression: nothing may change without SET SOUND ENABLED.
#   K2 realism mode, MicroVAX II (TQK50, THROTTLE 450K by default):
#        ATTACH -N (a new, empty cartridge) only inserts it, the unit has
#        no volume; SET TQ LOAD loads (10-15 s) and calibrates (2 min);
#        BACKUP save set and BACKUP/LIST with the guest's clock (tape time,
#        the reposition cycles: SHOW TQ TRANSPORT counts them); DISMOUNT
#        rewinds and unloads (the file stays attached, no volume);
#        SET TQ LOAD again (no calibration: the cartridge is not new),
#        BACKUP/LIST, DISMOUNT/NOUNLOAD
#   K3 realism mode, VAX-11/750 (TUK50 on the Unibus): as K2 with an
#        existing cartridge (the K2 tape: no calibration), BACKUP/LIST only
#
# Usage: python3 -I tktest.py <BIN directory> <VMS047-1.R81> <work dir> [K1|K2|K3 ...]
# The image is copied; the original is not changed.  The simulator output
# goes to <work dir>/<test>.log; with AUDIO=1 the audio (SDL disk driver)
# goes to <work dir>/<test>.raw (float mono 44100 Hz).
import sys, os, subprocess, shutil, time

def step(cmd, tag):
    """DCL command, then a marker line; the script stops at the marker."""
    return ('send after=500000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"\n'
            'expect "=%sEND="\ncontinue\n' % (cmd.replace('"', '\\"'), tag, tag))

def clock(tag):
    return step('WRITE SYS$OUTPUT "CLOCK ' + tag + ' ",F$TIME()', "K" + tag)

LOGIN = ('expect "job terminated" send after=2000000,"\\r"; continue\n'
         'expect "Username:" send "SYSTEM\\r"; continue\n'
         'expect "Password:" send "MANAGER\\r"; continue\n'
         'expect "Welcome"\n')

SMALL = "SYS$HELP:*.HLB"            # about 3 MB

def run(sim, ini, log, limit, audio):
    t = time.time()
    env = dict(os.environ)
    if audio:
        env["SDL_AUDIODRIVER"] = "disk"
        env["SDL_DISKAUDIOFILE"] = audio
    else:
        env["SDL_AUDIODRIVER"] = "dummy"
    with open(log, "wb") as f:
        subprocess.run([sim, ini], stdout=f, stderr=subprocess.STDOUT, timeout=limit,
                       env=env, stdin=subprocess.DEVNULL)
    txt = open(log, "rb").read().replace(b"\0", b"").decode("latin-1")
    return txt, time.time() - t

def main():
    bindir, image, work = sys.argv[1], sys.argv[2], sys.argv[3]
    which = sys.argv[4:] or ["K1", "K2", "K3"]
    os.makedirs(work, exist_ok=True)
    w = lambda f: os.path.join(work, f)
    audio_on = os.environ.get("AUDIO") == "1"
    res = []
    for test in which:
        t = test[1]
        vax750 = (test == "K3")
        real = test in ("K2", "K3")
        sim = os.path.join(bindir, "vax750" if vax750 else "microvax2")
        disk = w(test.lower() + ".vhd")
        shutil.copyfile(image, disk); os.chmod(disk, 0o644)
        tape = w("k2.tap" if test == "K3" else test.lower() + ".tap")
        if test != "K3" and os.path.exists(tape):
            os.remove(tape)
        s = "; %s (generated by tktest.py v1)\n" % test
        if real:                                 # before any ATTACH
            s += "set sound enabled\nshow sound\n"
        if vax750:
            s += "set cpu 8m\nset rq0 ra81\nattach rq0 %s\nset tq enable\n" % disk
        else:
            s += "set cpu 16m\nset rq0 ra81\nattach rq0 %s\n" % disk
        s += "attach %s tq0 %s\n" % ("" if test == "K3" else "-n", tape)
        s += "show tq0\n"
        if real:
            s += "echo ==== %s: after ATTACH (inserted)\nshow tq0 transport\n" % test
            s += "set tq0 load\necho ==== %s: after SET TQ0 LOAD\nshow tq0 transport\n" % test
        s += "show throttle\n"
        if vax750:
            s += "set runlimit 7200 seconds\n" + LOGIN + "boot rq0\n"
        else:
            s += ('set runlimit 7200 seconds\nexpect ">>>" send "B DUA0\\r"; continue\n'
                  'expect "HH:MM)" send "8-NOV-2026 15:00\\r"; continue\n') + LOGIN + "boot cpu\n"
        s += step("SET TERMINAL/WIDTH=132", t + "A")
        # VMS V4.7 initializes the TMSCP port (PTA0) only at the end of the
        # startup, MUA0 exists some 30 s later
        s += step("WAIT 00:00:40", t + "W")
        s += step("SHOW DEVICE MUA0:", t + "X")
        if test != "K3":
            s += step("INITIALIZE MUA0: TKTEST", t + "B")
            s += step("MOUNT/FOREIGN MUA0:", t + "C")
            s += clock(t + "1")
            s += step("BACKUP/NOLOG " + SMALL + " MUA0:T.BCK/SAVE_SET/REWIND/LABEL=TKTEST", t + "D")
            s += clock(t + "2")
            s += "echo ==== %s: after BACKUP\nshow tq0 transport\n" % test
        else:
            s += step("MOUNT/FOREIGN MUA0:", t + "C")
        s += clock(t + "3")
        s += step("BACKUP/LIST=SYS$LOGIN:L.LIS MUA0:T.BCK/SAVE_SET/REWIND", t + "E")
        s += clock(t + "4")
        s += "echo ==== %s: after BACKUP/LIST\nshow tq0 transport\n" % test
        s += step("SEARCH SYS$LOGIN:L.LIS \"Total of\"", t + "F")
        s += step("DISMOUNT MUA0:", t + "G")
        s += clock(t + "5")
        s += "echo ==== %s: after DISMOUNT (unloads)\nshow tq0\n" % test
        if real:
            s += "show tq0 transport\nset tq0 load\necho ==== %s: loaded again\nshow tq0 transport\n" % test
            s += step("MOUNT/FOREIGN MUA0:", t + "H")
            s += step("BACKUP/LIST MUA0:T.BCK/SAVE_SET/REWIND", t + "I")
            s += step("DISMOUNT/NOUNLOAD MUA0:", t + "J")
            s += "show tq0 transport\n"
        s += "exit\n"
        open(w(test.lower() + ".ini"), "w").write(s)
        audio = w(test.lower() + ".raw") if audio_on else None
        txt, secs = run(sim, w(test.lower() + ".ini"), w(test.lower() + ".log"), 7500, audio)
        res.append((test, secs, txt))
        print("%s: %.0f s wall" % (test, secs), flush=True)
    for test, secs, txt in res:
        print("==== %s" % test)
        for line in txt.splitlines():
            l = line.strip()
            if (l.startswith("CLOCK") or "TK50:" in l or l.startswith("====") or
                "Total of" in l or "%BACKUP" in l or "%MOUNT" in l or "%SYSTEM" in l or
                "throttle" in l.lower() or l.startswith("MUA0") or "-F-" in l or "-E-" in l or "attached to" in l):
                print("   " + l)

main()
