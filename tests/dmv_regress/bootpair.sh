#!/bin/bash
# open-simh-extended/tests/dmv_regress/bootpair.sh  v2 (v2: EXTRA="simh command" is put into both .ini files, e.g. EXTRA="set cpu idle=vms")
# Hang check: boot the two VMS V4.7 nodes at the same time, each with an
# attached DMV11 that has the other as PEER (as pair.sh does), only log in,
# and report whether each boot finished.  Repeated N times.
#   usage: bootpair.sh SIMULATOR N [nodmv]
#   nodmv: the same without any DMV11 (comparison)
SIM=$1; N=$2; MODE=$3
cd "$(dirname "$0")" || exit 1
for i in $(seq 1 $N); do
    for n in a b; do
        if [ $n = a ]; then MY=21301; PEER=21302; else MY=21302; PEER=21301; fi
        cp --sparse=always disk${n^^}.vhd bp_$n.vhd
        {
        echo "; bp_$n.ini - generated by bootpair.sh v2"
        echo "set cpu 16m"
        [ -n "$EXTRA" ] && echo "$EXTRA"
        echo "set rq0 ra81"
        echo "attach rq0 bp_$n.vhd"
        if [ "$MODE" != nodmv ]; then
            echo "set dmv enable"
            echo "set dmv0 peer=127.0.0.1:$PEER"
            echo "attach dmv0 $MY"
        fi
        echo 'expect ">>>" send "B DUA0\r"; continue'
        echo "boot cpu"
        } > bp_$n.ini
    done
    python3 -I vmsrun.py $SIM bp_a.ini bp_a.log alone.cmd 240 > bp_a.out 2>&1 &
    sleep 3
    python3 -I vmsrun.py $SIM bp_b.ini bp_b.log alone.cmd 240 > bp_b.out 2>&1
    wait
    pkill -f "bp_[ab].ini" 2>/dev/null
    echo "round $i: a=$(tail -1 bp_a.out | cut -c1-30)  b=$(tail -1 bp_b.out | cut -c1-30)"
done
