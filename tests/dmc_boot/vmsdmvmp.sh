#!/bin/bash
# open-simh-extended/tests/dmc_boot/vmsdmvmp.sh  v4 (2026-11-26; v4: P2P=1 point-to-point (line DMP-0 DDCMP POINT, circuit DMP-0; DMV0 MODE=FDXPOINT); v3: PDPREALISM=1 runs the PDP-11 with SET REALISM ENABLED, as Ulli's; v2: LOAD=1: NCP LOAD NODE from the VAX, with remote load detect on the PDP-11, password = tributary address 4)
#
# A PDP-11/73 whose DMV11 is a multipoint tributary (tributary 4, MODE=
# FDXTRIBUTARY, POWERONBOOT, Ulli's settings of 2026-11-26) boots with
# BOOT DMV0 from VMS V4.7 on a VAX-11/780 whose DMP11 is the control station
# (line DMP-0 DDCMP CONTROL, listening on 21301 without a PEER; circuit
# DMP-0.4 TRIBUTARY 4 SERVICE ENABLED).  VMS's node PDPDMV (1.21) has SERVICE
# CIRCUIT DMP-0.4, SERVICE DEVICE DMV, secondary loader HELLO.TSK.
# LOAD=1: the PDP-11 also has SET DMV0 REMOTELOAD and the VAX node SERVICE
# PASSWORD 4, and after the set-up VMS gives NCP LOAD NODE PDPDMV.
# PASS: HELLO's line on the PDP-11 console.
# PDPREALISM=1: the PDP-11 runs with SET REALISM ENABLED (Ulli's set-up).
# P2P=1: point-to-point instead: VAX line DMP-0 DDCMP POINT, circuit DMP-0
# (SERVICE ENABLED), node SERVICE CIRCUIT DMP-0; PDP-11 MODE=FDXPOINT.
# usage: [P2P=1] [PDPREALISM=1] [LOAD=1] [VAXDEBUG=flags] [PDPDEBUG=flags] LOADERS=dir vmsdmvmp.sh BINDIR DISK
BIN=$(readlink -f "$1"); DISK=$(readlink -f "$2")
[ -n "$LOADFILE" ] && LOADFILE=$(readlink -f "$LOADFILE")
[ -n "$BRURL" ] && BRURL=$(readlink -f "$BRURL")
LOADERS=$(readlink -f "${LOADERS:?LOADERS=dir with SECDUP.SYS and TERDUP.SYS}")
cd "$(dirname "$0")" || exit 1
PROGRAM=${PROGRAM:-SECONDARY}
MACRO11=${MACRO11:-/home/claude/macro11/macro11}
if [ "$P2P" = 1 ]; then LPROTO=POINT; CIRC=DMP-0; CTRIB=; PMODE=fdxpoint; R=run_dmvp2p; else LPROTO=CONTROL; CIRC=DMP-0.4; CTRIB="TRIBUTARY 4"; PMODE=fdxtributary; R=run_dmvmp; fi; rm -rf $R; mkdir -p $R
$MACRO11 -ysl 8 hello.mac -o $R/hello.obj -l $R/hello.lst || exit 1
(cd $R && python3 -I ../../dmv11_vmsload/obj2tsk.py hello.obj HELLO > /dev/null) || exit 1
if [ -n "$LOADFILE" ]; then cp "$LOADFILE" $R/LOADFILE.TSK; else cp $R/hello.tsk $R/LOADFILE.TSK; fi
python3 -I ../deuna_boot/mktap.py $R/dmcboot.tap $R/hello.tsk $R/LOADFILE.TSK $LOADERS/SECDUP.SYS $LOADERS/TERDUP.SYS > /dev/null
cp --sparse=always "$DISK" $R/vax.vhd
[ -n "$BRURL" ] && cp "$BRURL" $R/brusys.rl01
cat > $R/vax.ini <<EOT
; $R/vax.ini - generated by vmsdmvmp.sh v4: the VMS V4.7 control station and load host
set cpu 16m
set cpu idle=vms
set rq0 ra81
attach rq0 $R/vax.vhd
set ts enable
attach ts $R/dmcboot.tap
EOT
[ -n "$BRURL" ] && printf 'set rl enable\nattach rl0 %s\n' $R/brusys.rl01 >> $R/vax.ini
cat >> $R/vax.ini <<EOT
set dmp enable
attach dmp0 21301
set debug $R/vax.dbg
set dmp debug=${VAXDEBUG:-WARN}
boot rq0
EOT
cat > $R/vax.cmd <<'EOT'
MOUNT/FOREIGN/BLOCKSIZE=512/RECORDSIZE=512 MSA0:
COPY MSA0: SYS$SYSTEM:HELLO.TSK
COPY MSA0: SYS$SYSTEM:DUPLOAD.TSK
COPY MSA0: SYS$SYSTEM:SECDUP.SYS
COPY MSA0: SYS$SYSTEM:TERDUP.SYS
DISMOUNT MSA0:
EOT
if [ -n "$BRURL" ]; then
    printf '%s\n' 'MOUNT/OVERRIDE=IDENTIFICATION DLA0:' 'COPY DLA0:[006054]BRUSYS.SYS SYS$SYSTEM:DUPLOAD.TSK' 'DISMOUNT DLA0:' >> $R/vax.cmd
fi
cat >> $R/vax.cmd <<'EOT'
MC NCP PURGE KNOWN CIRCUITS ALL
MC NCP PURGE KNOWN LINES ALL
MC NCP DEFINE LINE DMP-0 STATE ON PROTOCOL DDCMP $LPROTO
MC NCP DEFINE CIRCUIT $CIRC STATE ON $CTRIB SERVICE ENABLED
@SYS$MANAGER:STARTNET
!WAIT 30
MC NCP SET NODE 1.21 NAME PDPDMV
MC NCP SET NODE PDPDMV SERVICE CIRCUIT $CIRC SERVICE DEVICE DMV CPU PDP11
MC NCP SET NODE PDPDMV SECONDARY LOADER SYS$SYSTEM:HELLO.TSK
MC NCP SET NODE PDPDMV LOAD FILE SYS$SYSTEM:HELLO.TSK
MC NCP SHOW CIRCUIT $CIRC CHARACTERISTICS
WRITE SYS$OUTPUT "DMCBOOT","-READY"
EOT
if [ "$LOAD" = 1 ]; then
    printf '%s\n' 'MC NCP SET NODE PDPDMV SERVICE PASSWORD 4' 'MC NCP LOAD NODE PDPDMV' >> $R/vax.cmd
fi
echo '!WAIT 150' >> $R/vax.cmd
echo "MC NCP SHOW CIRCUIT $CIRC STATUS" >> $R/vax.cmd
{
    echo "; $R/pdp.ini - generated by vmsdmvmp.sh v4: the PDP-11 tributary that boots"
    echo "set cpu 11/73"
    [ "$PDPREALISM" = 1 ] && echo "set realism enabled"
    echo "set dmv enable"
    echo "set dmv0 tributary=4"
    echo "set dmv0 peer=127.0.0.1:21301"
    echo "attach dmv0 21302"
    echo "set dmv0 poweronboot"
    [ "$LOAD" = 1 ] && echo "set dmv0 remoteload"
    echo "set dmv0 mode=$PMODE"
    echo "set debug $R/pdp.dbg"
    [ -n "$PDPDEBUG" ] && echo "set dmv debug=$PDPDEBUG"
    echo "set runlimit 200 seconds"
    echo "boot dmv0"
    echo "echo START-REGS"
    echo "exa r1,r2,sp,pc"
} > $R/pdp.ini
# the command file is written with quoted here-documents: fill in the line
# protocol, circuit and tributary parameter of P2P here
sed -i "s/\$LPROTO/$LPROTO/g; s/\$CIRC/$CIRC/g; s/ \$CTRIB/${CTRIB:+ $CTRIB}/g" $R/vax.cmd
python3 -I ../dmv_regress/vmsrun.py $BIN/vax780 $R/vax.ini $R/vax.log $R/vax.cmd 1200 > $R/vax.out 2>&1 &
for i in $(seq 1 120); do                     # wait for the load host
    grep -aq "DMCBOOT-READY" $R/vax.log 2>/dev/null && break
    sleep 5
done
grep -aq "DMCBOOT-READY" $R/vax.log || { echo "DMV MP $PROGRAM FAIL (the load host did not get ready)"; wait; exit 1; }
SDL_AUDIODRIVER=dummy timeout 320 $BIN/pdp11 $R/pdp.ini < /dev/null 2>&1 | tr -d '\r' > $R/pdp.out
wait
tr -d '\r' < $R/vax.log | grep -a -E "Load, |File =|Circuit DMC-0"
grep -v "^\s*$" $R/pdp.out | sed -n '/boot dmv0/,$p'
# PASS: HELLO's line; with another LOADFILE (which prints what it likes)
# VMS's "Load, Successful" for the operating system
if grep -q "HELLO from the VMS load host" $R/pdp.out ||
   { [ -n "$LOADFILE$BRURL" ] && tr -d '\r' < $R/vax.log | grep -aq "Load, Successful"; }; then
    echo "DMV MP $PROGRAM PASS"
else
    echo "DMV MP $PROGRAM FAIL"
fi
