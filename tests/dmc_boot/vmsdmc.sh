#!/bin/bash
# open-simh-extended/tests/dmc_boot/vmsdmc.sh  v2 (v2: PDPPEER, default 21399 so that only the VAX connection is used (known issue 116: crossing connections); PASS also on "Load, Successful" with LOADFILE; VAXDEBUG/PDPDEBUG)
#
# SIMH's BOOT DMCn (patch 24) with a real load host: VMS V4.7 on a
# VAX-11/780 with a DMC11 (VMS line and circuit DMC-0) loads a PDP-11/34
# whose DMC11 (or DMR11 with TYPE=DMR) is joined to it by a SIMH TCP line
# (VAX listens on 21301 and connects to 21302; the PDP-11 listens on 21302
# and has PEER=PDPPEER, default 21399 where nobody listens, so that only the
# VAX's connection is used; known issue 116).
#   VAX:    boots a copy of DISK (VMS V4.7, node VAX4 1.4, SYSTEM/MANAGER),
#           copies HELLO.TSK and the load file from a tape (TS11, MSA0)
#           into SYS$SYSTEM, defines line/circuit DMC-0 with SERVICE
#           ENABLED, starts DECnet, defines node PDPDMC (1.21) with
#           SERVICE CIRCUIT DMC-0, SERVICE DEVICE DMC, CPU PDP11,
#           SECONDARY LOADER HELLO.TSK and LOAD FILE (HELLO.TSK or
#           LOADFILE), then waits (WAITLOAD=0) or gives NCP LOAD NODE
#           PDPDMC (WAITLOAD=1: the host starts the load, the bootstrap's
#           repeated Request Program is answered)
#   PDP-11: BOOT DMC0 with SET DMC0 PROGRAM=$PROGRAM (SECONDARY: VMS sends
#           HELLO.TSK in one Memory Load with Transfer Address; SYSTEM: the
#           load file in Memory Loads); a breakpoint at the program's start
#           shows R1 = the CSR; HELLO prints its line and halts.
# PASS: HELLO's line on the PDP-11 console; with LOADFILE, VMS's "Load,
# Successful" (the load file prints what it likes).
# Needs: ../dmv_regress/vmsrun.py, macro11 (MACRO11=path), the VMS disk.
#
# usage: [PROGRAM=SECONDARY|SYSTEM] [LOADFILE=file.tsk] [TYPE=DMC|DMR]
#        [WAITLOAD=0|1] [START=octal] [VAXDEBUG=flags] [PDPDEBUG=flags]
#        [PDPPEER=port]
#        vmsdmc.sh BINDIR DISK
#   VAXDEBUG, PDPDEBUG: SET DMC DEBUG= flags of the two simulators
#   (default WARN and INFO;WARN; logs vax.dbg, pdp.dbg)
#   START: the program's start address for the breakpoint (default: none)
BIN=$(readlink -f "$1"); DISK=$(readlink -f "$2")
[ -n "$LOADFILE" ] && LOADFILE=$(readlink -f "$LOADFILE")
cd "$(dirname "$0")" || exit 1
PROGRAM=${PROGRAM:-SECONDARY}; TYPE=${TYPE:-DMC}; WAITLOAD=${WAITLOAD:-0}
MACRO11=${MACRO11:-/home/claude/macro11/macro11}
R=run_$(echo $PROGRAM | tr A-Z a-z)_$TYPE; rm -rf $R; mkdir -p $R
$MACRO11 -ysl 8 hello.mac -o $R/hello.obj -l $R/hello.lst || exit 1
(cd $R && python3 -I ../../dmv11_vmsload/obj2tsk.py hello.obj HELLO > /dev/null) || exit 1
if [ -n "$LOADFILE" ]; then cp "$LOADFILE" $R/LOADFILE.TSK; else cp $R/hello.tsk $R/LOADFILE.TSK; fi
python3 -I ../deuna_boot/mktap.py $R/dmcboot.tap $R/hello.tsk $R/LOADFILE.TSK > /dev/null
cp --sparse=always "$DISK" $R/vax.vhd
cat > $R/vax.ini <<EOT
; $R/vax.ini - generated by vmsdmc.sh v1: the VMS V4.7 load host
set cpu 16m
set cpu idle=vms
set rq0 ra81
attach rq0 $R/vax.vhd
set ts enable
attach ts $R/dmcboot.tap
set dmc enable
set dmc0 type=$TYPE
set dmc0 peer=127.0.0.1:21302
attach dmc0 21301
set debug $R/vax.dbg
set dmc debug=${VAXDEBUG:-WARN}
boot rq0
EOT
cat > $R/vax.cmd <<'EOT'
MOUNT/FOREIGN/BLOCKSIZE=512/RECORDSIZE=512 MSA0:
COPY MSA0: SYS$SYSTEM:HELLO.TSK
COPY MSA0: SYS$SYSTEM:DMCLOAD.TSK
DISMOUNT MSA0:
MC NCP PURGE KNOWN CIRCUITS ALL
MC NCP PURGE KNOWN LINES ALL
MC NCP DEFINE LINE DMC-0 STATE ON
MC NCP DEFINE CIRCUIT DMC-0 STATE ON SERVICE ENABLED
@SYS$MANAGER:STARTNET
!WAIT 30
MC NCP SET NODE 1.21 NAME PDPDMC
MC NCP SET NODE PDPDMC SERVICE CIRCUIT DMC-0 SERVICE DEVICE DMC CPU PDP11
MC NCP SET NODE PDPDMC SECONDARY LOADER SYS$SYSTEM:HELLO.TSK
MC NCP SET NODE PDPDMC LOAD FILE SYS$SYSTEM:DMCLOAD.TSK
MC NCP SHOW CIRCUIT DMC-0 CHARACTERISTICS
WRITE SYS$OUTPUT "DMCBOOT","-READY"
EOT
if [ "$WAITLOAD" = 1 ]; then
    echo "MC NCP LOAD NODE PDPDMC" >> $R/vax.cmd
fi
echo '!WAIT 150' >> $R/vax.cmd
echo 'MC NCP SHOW CIRCUIT DMC-0 STATUS' >> $R/vax.cmd
{
    echo "; $R/pdp.ini - generated by vmsdmc.sh v1: the PDP-11 that boots"
    echo "set cpu 11/34"
    echo "set cpu 64k"
    echo "set dmc enable"
    echo "set dmc0 type=$TYPE"
    echo "set dmc0 program=$PROGRAM"
    # PDPPEER: the PDP-11's PEER port (a DMC needs one).  Default 21399, where
    # nobody listens: only the VAX's connection is used.  With 21301 (the
    # VAX) both sides connect: the PDP-11's connection was up at once, but
    # the VAX took it as the line only much later, so the bootstrap's
    # repeated Request Programs waited in it and reached VMS in a burst,
    # some in the middle of the load (known issue 116).
    echo "set dmc0 peer=127.0.0.1:${PDPPEER:-21399}"
    echo "attach dmc0 21302"
    echo "set debug $R/pdp.dbg"
    echo "set dmc debug=${PDPDEBUG:-INFO;WARN}"
    echo "set runlimit 300 seconds"
    [ -n "$START" ] && echo "break $START"
    echo "boot dmc0"
    echo "echo START-REGS"
    echo "exa r1,r2,sp,pc"
    [ -n "$START" ] && { echo "nobreak $START"; echo "continue"; echo "exa r1,r2,sp,pc"; }
} > $R/pdp.ini
python3 -I ../dmv_regress/vmsrun.py $BIN/vax780 $R/vax.ini $R/vax.log $R/vax.cmd 1200 > $R/vax.out 2>&1 &
for i in $(seq 1 120); do                     # wait for the load host
    grep -aq "DMCBOOT-READY" $R/vax.log 2>/dev/null && break
    sleep 5
done
grep -aq "DMCBOOT-READY" $R/vax.log || { echo "DMC VMS $PROGRAM FAIL (the load host did not get ready)"; wait; exit 1; }
SDL_AUDIODRIVER=dummy timeout 320 $BIN/pdp11 $R/pdp.ini < /dev/null 2>&1 | tr -d '\r' > $R/pdp.out
wait
tr -d '\r' < $R/vax.log | grep -a -E "Load, |File =|Circuit DMC-0"
grep -v "^\s*$" $R/pdp.out | sed -n '/boot dmc0/,$p'
# PASS: HELLO's line; with another LOADFILE (which prints what it likes)
# VMS's "Load, Successful" for the operating system
if grep -q "HELLO from the VMS load host over the DMC11" $R/pdp.out ||
   { [ -n "$LOADFILE" ] && tr -d '\r' < $R/vax.log | grep -aq "Load, Successful"; }; then
    echo "DMC VMS $PROGRAM $TYPE PASS"
else
    echo "DMC VMS $PROGRAM $TYPE FAIL"
fi
