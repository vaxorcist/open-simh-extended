#!/bin/bash
# open-simh-extended/tests/dmc_boot/vmsdup.sh  v3 (2026-11-28; v3: MINNODE=1 defines the node without SERVICE DEVICE and CPU (Ulli's SET_xxxPOINT-DUP.COM); PDPREALISM=1 runs the PDP-11 with SET REALISM ENABLED; VAXDEV=DMF: the VAX uses its DMF32 sync line (DMF-SYNC, VMS DMF-0) instead of the DMC11; v2 2026-11-25, patch 28; v2: BRURL=brusys.rl01 loads Ulli's RSX-11M standalone BRU, PDPMEM)
#
# SIMH's BOOT DUPn with a real load host: VMS V4.7 on a VAX-11/780 with a
# DMC11 (line and circuit DMC-0) loads a PDP-11/34 whose DUP11 is joined to
# it by a SIMH TCP line (VAX listens on 21301 and connects to 21302; the
# PDP-11's DUP0 listens on 21302 and connects to 21301).  The DUP11 has no
# boot logic: BOOT DUP0 starts SIMH's MOP bootstrap (pdp11_dup_boot.mac).
#   VAX:    boots a copy of DISK (VMS V4.7, node VAX4 1.4, SYSTEM/MANAGER),
#           copies HELLO.TSK, the load file and DEC's DUP11 loaders
#           SECDUP.SYS/TERDUP.SYS from a tape into SYS$SYSTEM, defines
#           line/circuit DMC-0 with SERVICE ENABLED, starts DECnet, defines
#           node PDPDUP (1.22) with SERVICE CIRCUIT DMC-0, SERVICE DEVICE
#           DUP, CPU PDP11, SECONDARY LOADER SECDUP.SYS, TERTIARY LOADER
#           TERDUP.SYS and LOAD FILE (HELLO.TSK or LOADFILE)
#   PDP-11: BOOT DUP0 with SET DUP0 PROGRAM=$PROGRAM:
#           SECONDARY - VMS sends SECDUP.SYS, which loads TERDUP.SYS, which
#                       loads the load file (DEC's loaders drive the DUP11
#                       with CRC inhibit: known issue 124);
#           SYSTEM    - VMS sends the load file to the bootstrap directly.
#           HELLO prints its line and halts.
# BRURL=brusys.rl01 (Ulli's RL01 with [006054]BRUSYS.SYS, never in the
# repository): the VAX copies BRUSYS.SYS from it (RL0, DLA0:) as the load
# file (BRU runs in the default 64 KB; PDPMEM is a SET CPU size, e.g. 128k).
# PASS: HELLO's line on the PDP-11 console; with LOADFILE or BRURL, VMS's
# "Load, Successful" (the load file prints what it likes).
# Needs: ../dmv_regress/vmsrun.py, macro11 (MACRO11=path), the VMS disk,
# and DEC's SECDUP.SYS and TERDUP.SYS in LOADERS (DEC kit files: never in
# the repository; the run directory is ignored).
#
# usage: [PROGRAM=SECONDARY|SYSTEM] [LOADFILE=file.tsk] [VAXDEBUG=flags]
#        [PDPDEBUG=flags] [BRURL=brusys.rl01] [PDPMEM=64k]
#        [VAXDEV=DMC|DMF] [MINNODE=1] [PDPREALISM=1] LOADERS=dir vmsdup.sh BINDIR DISK
#   VAXDEV=DMF: VAX DMF32 sync line (unit DMF-SYNC; VMS line/circuit DMF-0,
#   PROTOCOL DDCMP POINT) in place of the DMC11 (VAXDEBUG then sets DMF
#   debug flags)
#   VAXDEBUG: SET DMC DEBUG= flags of the VAX (default WARN, vax.dbg);
#   PDPDEBUG: SET DUP DEBUG= flags of the PDP-11 (default none, pdp.dbg)
BIN=$(readlink -f "$1"); DISK=$(readlink -f "$2")
[ -n "$LOADFILE" ] && LOADFILE=$(readlink -f "$LOADFILE")
[ -n "$BRURL" ] && BRURL=$(readlink -f "$BRURL")
LOADERS=$(readlink -f "${LOADERS:?LOADERS=dir with SECDUP.SYS and TERDUP.SYS}")
cd "$(dirname "$0")" || exit 1
PROGRAM=${PROGRAM:-SECONDARY}
MACRO11=${MACRO11:-/home/claude/macro11/macro11}
VAXDEV=${VAXDEV:-DMC}
if [ "$VAXDEV" = DMF ]; then
    VAXLINK="set dmf enable
set dmf-sync peer=127.0.0.1:21302
attach dmf-sync 21301"; VDEVDBG=dmf; VDEFDBG=SXMT; VCIRC=DMF-0; VPROTO="PROTOCOL DDCMP POINT"
else
    VAXLINK="set dmc enable
set dmc0 type=DMC
set dmc0 peer=127.0.0.1:21302
attach dmc0 21301"; VDEVDBG=dmc; VDEFDBG=WARN; VCIRC=DMC-0; VPROTO=
fi
R=run_${VAXDEV}_$(echo $PROGRAM | tr A-Z a-z)_DUP${BRURL:+_BRU}; rm -rf $R; mkdir -p $R
$MACRO11 -ysl 8 hello.mac -o $R/hello.obj -l $R/hello.lst || exit 1
(cd $R && python3 -I ../../dmv11_vmsload/obj2tsk.py hello.obj HELLO > /dev/null) || exit 1
if [ -n "$LOADFILE" ]; then cp "$LOADFILE" $R/LOADFILE.TSK; else cp $R/hello.tsk $R/LOADFILE.TSK; fi
python3 -I ../deuna_boot/mktap.py $R/dmcboot.tap $R/hello.tsk $R/LOADFILE.TSK $LOADERS/SECDUP.SYS $LOADERS/TERDUP.SYS > /dev/null
cp --sparse=always "$DISK" $R/vax.vhd
[ -n "$BRURL" ] && cp "$BRURL" $R/brusys.rl01
cat > $R/vax.ini <<EOT
; $R/vax.ini - generated by vmsdup.sh v3: the VMS V4.7 load host
set cpu 16m
set cpu idle=vms
set rq0 ra81
attach rq0 $R/vax.vhd
set ts enable
attach ts $R/dmcboot.tap
EOT
[ -n "$BRURL" ] && printf 'set rl enable\nattach rl0 %s\n' $R/brusys.rl01 >> $R/vax.ini
cat >> $R/vax.ini <<EOT
$VAXLINK
set debug $R/vax.dbg
set $VDEVDBG debug=${VAXDEBUG:-$VDEFDBG}
boot rq0
EOT
cat > $R/vax.cmd <<'EOT'
MOUNT/FOREIGN/BLOCKSIZE=512/RECORDSIZE=512 MSA0:
COPY MSA0: SYS$SYSTEM:HELLO.TSK
COPY MSA0: SYS$SYSTEM:DUPLOAD.TSK
COPY MSA0: SYS$SYSTEM:SECDUP.SYS
COPY MSA0: SYS$SYSTEM:TERDUP.SYS
DISMOUNT MSA0:
EOT
if [ -n "$BRURL" ]; then
    printf '%s\n' 'MOUNT/OVERRIDE=IDENTIFICATION DLA0:' 'COPY DLA0:[006054]BRUSYS.SYS SYS$SYSTEM:DUPLOAD.TSK' 'DISMOUNT DLA0:' >> $R/vax.cmd
fi
cat >> $R/vax.cmd <<'EOT'
MC NCP PURGE KNOWN CIRCUITS ALL
MC NCP PURGE KNOWN LINES ALL
MC NCP DEFINE LINE $VCIRC STATE ON $VPROTO
MC NCP DEFINE CIRCUIT $VCIRC STATE ON SERVICE ENABLED
@SYS$MANAGER:STARTNET
!WAIT 30
MC NCP SET NODE 1.22 NAME PDPDUP
MC NCP SET NODE PDPDUP SERVICE CIRCUIT $VCIRC SERVICE DEVICE DUP CPU PDP11
MC NCP SET NODE PDPDUP SECONDARY LOADER SYS$SYSTEM:SECDUP.SYS
MC NCP SET NODE PDPDUP TERTIARY LOADER SYS$SYSTEM:TERDUP.SYS
MC NCP SET NODE PDPDUP LOAD FILE SYS$SYSTEM:DUPLOAD.TSK
MC NCP SHOW CIRCUIT $VCIRC CHARACTERISTICS
WRITE SYS$OUTPUT "DMCBOOT","-READY"
EOT
echo '!WAIT 150' >> $R/vax.cmd
echo 'MC NCP SHOW CIRCUIT $VCIRC STATUS' >> $R/vax.cmd
{
    echo "; $R/pdp.ini - generated by vmsdup.sh v3: the PDP-11 that boots"
    echo "set cpu ${PDPCPU:-11/34}"
    [ "$PDPREALISM" = 1 ] && echo "set realism enabled"
    echo "set cpu ${PDPMEM:-64k}"
    echo "set dup enable"
    echo "set dup0 program=$PROGRAM"
    echo "attach dup0 21302,connect=127.0.0.1:21301"
    echo "set debug $R/pdp.dbg"
    [ -n "$PDPDEBUG" ] && echo "set dup debug=$PDPDEBUG"
    echo "set runlimit 300 seconds"
    echo "boot dup0"
    echo "echo START-REGS"
    echo "exa r1,r2,sp,pc"
} > $R/pdp.ini
# the command file is written with quoted here-documents: fill in the VAX
# side's line/circuit and protocol here (VAXDEV)
sed -i "s/\$VCIRC/$VCIRC/g; s/ \$VPROTO/${VPROTO:+ $VPROTO}/g" $R/vax.cmd
[ "$MINNODE" = 1 ] && sed -i "s/ SERVICE DEVICE DUP CPU PDP11//" $R/vax.cmd
python3 -I ../dmv_regress/vmsrun.py $BIN/vax780 $R/vax.ini $R/vax.log $R/vax.cmd 1200 > $R/vax.out 2>&1 &
for i in $(seq 1 120); do                     # wait for the load host
    grep -aq "DMCBOOT-READY" $R/vax.log 2>/dev/null && break
    sleep 5
done
grep -aq "DMCBOOT-READY" $R/vax.log || { echo "DUP VMS $PROGRAM FAIL (the load host did not get ready)"; wait; exit 1; }
SDL_AUDIODRIVER=dummy timeout 320 $BIN/pdp11 $R/pdp.ini < /dev/null 2>&1 | tr -d '\r' > $R/pdp.out
wait
tr -d '\r' < $R/vax.log | grep -a -E "Load, |File =|Circuit $VCIRC"
grep -v "^\s*$" $R/pdp.out | sed -n '/boot dup0/,$p'
# PASS: HELLO's line; with another LOADFILE (which prints what it likes)
# VMS's "Load, Successful" for the operating system
if grep -q "HELLO from the VMS load host" $R/pdp.out ||
   { [ -n "$LOADFILE$BRURL" ] && tr -d '\r' < $R/vax.log | grep -aq "Load, Successful"; }; then
    echo "DUP VMS $PROGRAM PASS"
else
    echo "DUP VMS $PROGRAM FAIL"
fi
