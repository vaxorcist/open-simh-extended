# open-simh-extended/tests/klesib/mkini.py  v1
#
# Generates the KLESI-B (TB) test scripts for the VAX 8200 (VMS V4.7, Ulli's
# image VMS047_1.R81 on the KDB50, SYSTEM/MANAGER; 2026-11-16).  Each DCL
# command is one expect step ending in a marker line, so the console never
# gets more than one command of type-ahead (several commands in one SEND
# overran VMS's type-ahead buffer: DATAOVERUN).
#
#   b1.ini  DWBUA + KLESI-B: SYSGEN SHOW/ADAPTER and SHOW/CONFIGURATION
#           (node 8 "BI - LESI Adapter", port PTB at 774500), INITIALIZE
#           MUB0 (TU81 on TB0, a new tape), BACKUP SYS$HELP:*.HLB, BACKUP/
#           LIST, restore to [TBR], DIFFERENCES HELPLIB.HLB, DISMOUNT
#   b2.ini  VAXBI-only (SET UBA DISABLE): SYSGEN (no UB0, the port is PTA),
#           the b1 tape on MUA0: BACKUP/LIST, a second save set appended,
#           BACKUP/LIST of it, DISMOUNT
#   b3.ini  VAX 8300 (two CPUs), VAXBI-only: as b2 with the b1 tape
#   b4.ini  regression: TU81 on the TQ (TUK50 on the DWBUA), TB disabled,
#           the b1 tape on MUA0: BACKUP/LIST; SHOW DEVICE P (port errors)
#
# Usage: python3 mkini.py <dir>   (writes b1.ini, b2.ini, b3.ini there)
# Run:   cd <dir>; cp VMS047_1.R81 here; vax8200 b1.ini > b1.log
#        (b2, b3 and b4 use b1's tb0.tap: copy it to tb0_b2.tap, tb0_b3.tap,
#        tb0_b4.tap)
import sys, os

def step(cmd, tag):
    return ('expect "=%sEND=" send after=300000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"; continue\n'
            % (tag[0], cmd.replace('"', '\\"').replace("\x00", "\\r"), tag[1]))

def script(name, head, cmds, title):
    s = "; open-simh-extended/tests/klesib/%s  v1 (generated by mkini.py v1)\n; %s\n" % (name, title)
    s += head
    s += ('expect "HH:MM)" send "16-NOV-2026 18:00\\r"; continue\n'
          'expect "job terminated" send after=2000000,"\\r"; continue\n'
          'expect "Username:" send "SYSTEM\\r"; continue\n'
          'expect "Password:" send "MANAGER\\r"; continue\n'
          'expect "$ " send after=500000,"WRITE SYS$OUTPUT \\"=S0\\",\\"END=\\"\\r"; continue\n')
    prev = "S0"
    for i, c in enumerate(cmds):
        tag = "S%d" % (i + 1)
        s += step(c, (prev, tag))
        prev = tag
    s += 'expect "=%sEND=" echof "\\n*** %s done"; exit\nboot kdb0\n' % (prev, name)
    return s

# SYSGEN in one step (its prompts take the lines; the marker follows EXIT).
# The WAIT: VMS V4.7 starts the TMSCP ports at the end of the startup.
SYSGEN = ["WAIT 00:01:30", "RUN SYS$SYSTEM:SYSGEN\x00SHOW/ADAPTER\x00SHOW/CONFIGURATION\x00EXIT"]

def main():
    d = sys.argv[1]
    common = "set cpu 16m\nset kdb0 ra81\nattach kdb0 VMS047_1.R81\nset tb enable\n"
    b1 = script("b1.ini", common + "attach tb0 -n tb0.tap\nset runlimit 1500 seconds\n",
        SYSGEN + ["SHOW DEVICE MU",
         "INITIALIZE MUB0: TBTEST", "MOUNT/FOREIGN MUB0:",
         "BACKUP/NOLOG SYS$HELP:*.HLB MUB0:T.BCK/SAVE_SET/REWIND/LABEL=TBTEST",
         "BACKUP/LIST=SYS$LOGIN:L.LIS MUB0:T.BCK/SAVE_SET/REWIND",
         'SEARCH SYS$LOGIN:L.LIS "Total of"',
         "CREATE/DIRECTORY SYS$SYSDEVICE:[TBR]",
         "BACKUP MUB0:T.BCK/SAVE_SET/REWIND SYS$SYSDEVICE:[TBR]*.*",
         "DIFFERENCES SYS$HELP:HELPLIB.HLB SYS$SYSDEVICE:[TBR]HELPLIB.HLB",
         "DIRECTORY/TOTAL SYS$SYSDEVICE:[TBR]",
         "DISMOUNT MUB0:", "SHOW DEVICE MU"],
        "DWBUA + KLESI-B: TU81 on TB0 is MUB0 (TQ is MUA0)")
    tail = ["SHOW DEVICE/BRIEF", "MOUNT/FOREIGN MUA0:",
         "BACKUP/LIST=SYS$LOGIN:L2.LIS MUA0:T.BCK/SAVE_SET/REWIND",
         'SEARCH SYS$LOGIN:L2.LIS "Total of"',
         "BACKUP/NOLOG SYS$SYSTEM:SYSGEN.EXE MUA0:S.BCK/SAVE_SET",
         "BACKUP/LIST MUA0:S.BCK/SAVE_SET/REWIND",
         "DISMOUNT MUA0:"]
    b2 = script("b2.ini", "set uba disable\n" + common + "attach tb0 tb0_b2.tap\nset runlimit 1500 seconds\n",
        SYSGEN + tail, "VAXBI-only (SET UBA DISABLE): the KLESI-B's TU81 is MUA0")
    b3 = script("b3.ini", "set ka1 enable\nset uba disable\n" + common + "attach tb0 tb0_b3.tap\nset runlimit 1500 seconds\n",
        SYSGEN + tail, "VAX 8300, VAXBI-only: the KLESI-B's TU81 is MUA0 (SYSGEN: both CPUs)")
    # b4: regression, the TQ (TUK50, TU81) on the DWBUA, TB disabled; the b1 tape
    b4 = script("b4.ini", "set cpu 16m\nset kdb0 ra81\nattach kdb0 VMS047_1.R81\nattach tq0 tb0_b4.tap\nset runlimit 1500 seconds\n",
        SYSGEN + ["SHOW DEVICE/BRIEF P", "SHOW DEVICE MU", "MOUNT/FOREIGN MUA0:",
         "BACKUP/LIST=SYS$LOGIN:L4.LIS MUA0:T.BCK/SAVE_SET/REWIND",
         'SEARCH SYS$LOGIN:L4.LIS "Total of"', "DISMOUNT MUA0:"],
        "Regression: TU81 on the TQ (TUK50, DWBUA), TB disabled: MUA0")
    for n, s in (("b1.ini", b1), ("b2.ini", b2), ("b3.ini", b3), ("b4.ini", b4)):
        open(os.path.join(d, n), "w").write(s)

main()
