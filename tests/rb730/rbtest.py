# open-simh-extended/tests/rb730/rbtest.py  v4 (v4: image and tool paths from the environment; v3: --layout, --rbset)
# Repeatable RB730 regression test set (VAX-11/730 RB80 + RB02 under VMS V3.5,
# RL02 interchange on the VAX-11/750 RL11).  Generates the SIMH scripts, runs
# them with the given simulators and checks the console logs.
#
# Usage: python3 -I rbtest.py <vax730 binary> <vax750 binary> <work dir>
#        [--rb80 image] [--layout old|std] [--rbset "SET command"]...
#   --layout old  the RB80 base image is in the old (head-major) SIMH layout
#                 and the simulator needs SET RBn LAYOUT=OLD (or has no layout
#                 option at all: upstream); the RB02 test cartridge is
#                 converted to the RL layout for the RL11 test.
#   --layout std  standard (DEC logical block) layout: the RB02 cartridge is
#                 used on the RL11 unchanged.
#   --rbset       extra SIMH commands before the ATTACHes (e.g. "set rb0 layout=old")
#
# Disk images (not part of the repository) and the tools directory:
#   RBTEST_RB80   VMS V3.5 system disk for the RB80 (default for --rb80)
#   RBTEST_RP06   VMS V3.5 system disk for the VAX-11/750 RP06
#   RBTEST_TOOLS  directory with rb730_layout_convert.py (default: ../../tools
#                 relative to this script, i.e. the tools/ directory of the
#                 notes branch)
#
# Tests:
#   T1 (vax730): boot from the RB80 (DQA0), log in, SHOW DEVICE DQ, MOUNT on an
#      RB02 unit without a cartridge (DQA2: the message is recorded),
#      INITIALIZE/MOUNT a blank RB02 (DQA1), COPY SYSGEN.EXE to it, DIRECTORY,
#      DUMP block 21, DISMOUNT.
#   T2 (vax750, VMS V3.5 on the RP06): the RB02 cartridge from T1 on the RL11
#      (DLA0): MOUNT, DIRECTORY, DUMP block 21 (must equal T1's).
import sys, os, subprocess, shutil, re, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
# Paths come from the environment (see the header); the tools directory
# defaults to the notes branch's tools/, two levels above this script.
TOOLS = os.environ.get("RBTEST_TOOLS", os.path.join(HERE, "..", "..", "tools"))
RB80_BASE = os.environ.get("RBTEST_RB80", "base.rb80")     # VMS V3.5 RB80 (old layout by default)
RP06_BASE = os.environ.get("RBTEST_RP06", "base.rp06")     # VMS V3.5 RP06 for the 750
RB02_SIZE = 10485760

def step(cmd, tag):
    return ('send after=1000000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"\n'
            'expect "=%sEND="\ncontinue\n' % (cmd.replace('"', '\\"'), tag, tag))

def login(boot):
    return ('expect "HH:MM)" send "4-NOV-1989 10:00\\r"; continue\n'
            'expect "job terminated" send after=3000000,"\\r"; continue\n'
            'expect "Username:" send "SYSTEM\\r"; continue\n'
            'expect "Password:" send "MANAGER\\r"; continue\n'
            'expect "Welcome"\n' + boot + '\n')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vax730"); ap.add_argument("vax750"); ap.add_argument("work")
    ap.add_argument("--rb80", default=RB80_BASE)
    ap.add_argument("--layout", choices=["old", "std"], default="old")
    ap.add_argument("--rbset", action="append", default=[])
    a = ap.parse_args()
    os.makedirs(a.work, exist_ok=True)
    w = lambda f: os.path.join(a.work, f)
    shutil.copyfile(a.rb80, w("t1.rb80")); os.chmod(w("t1.rb80"), 0o644)
    open(w("t1.rb02"), "wb").truncate(RB02_SIZE)
    shutil.copyfile(RP06_BASE, w("t2.rp06"))

    t1 = "; T1 (generated by rbtest.py v3)\nset cpu 4m\n" + "".join(c + "\n" for c in a.rbset)
    t1 += "attach rb0 t1.rb80\nattach rb1 t1.rb02\nset runlimit 1200 seconds\n" + login("boot rb0")
    t1 += step("SET TERMINAL/WIDTH=132", "A")
    t1 += step("WAIT 00:00:05", "B")
    t1 += step("SHOW DEVICE DQ", "C")
    t1 += step("MOUNT/NOASSIST DQA2: NOTHERE", "D")
    t1 += step("INITIALIZE DQA1: RB02T", "E")
    t1 += step("MOUNT DQA1: RB02T", "F")
    t1 += step("COPY SYS$SYSTEM:SYSGEN.EXE DQA1:[000000]X.TMP", "G")
    t1 += step("DIRECTORY/SIZE DQA1:[000000]", "H")
    t1 += step("DUMP/BLOCK=(START:21,COUNT:1) DQA1:[000000]X.TMP", "I")
    t1 += step("DISMOUNT DQA1:", "J")
    t1 += "exit\n"
    open(w("t1.ini"), "w").write(t1)

    r = subprocess.run([a.vax730, "t1.ini"], cwd=a.work, stdin=subprocess.DEVNULL,
                       stdout=open(w("t1.log"), "w"), stderr=subprocess.STDOUT,
                       env=dict(os.environ, SDL_AUDIODRIVER="dummy"), timeout=1800)
    log1 = open(w("t1.log"), errors="replace").read().replace("\r", "")

    cart = w("t1.rb02")
    if a.layout == "old":
        subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "rb730_layout_convert.py"),
                        "old2std", "rb02", cart, w("t2.rl02")], check=True, stdout=subprocess.DEVNULL)
    else:
        shutil.copyfile(cart, w("t2.rl02"))
    t2 = "; T2 (generated by rbtest.py v3)\nset cpu 8m\nset rp0 rp06\nattach rp0 t2.rp06\n"
    t2 += "set rl0 rl02\nattach rl0 t2.rl02\nset runlimit 900 seconds\n" + login("boot rp0")
    t2 += step("SET TERMINAL/WIDTH=132", "A")
    t2 += step("MOUNT DLA0: RB02T", "B")
    t2 += step("DIRECTORY/SIZE DLA0:[000000]", "C")
    t2 += step("DUMP/BLOCK=(START:21,COUNT:1) DLA0:[000000]X.TMP", "D")
    t2 += step("DISMOUNT DLA0:", "E")
    t2 += "exit\n"
    open(w("t2.ini"), "w").write(t2)
    subprocess.run([a.vax750, "t2.ini"], cwd=a.work, stdin=subprocess.DEVNULL,
                   stdout=open(w("t2.log"), "w"), stderr=subprocess.STDOUT,
                   env=dict(os.environ, SDL_AUDIODRIVER="dummy"), timeout=1800)
    log2 = open(w("t2.log"), errors="replace").read().replace("\r", "")

    def section(log, start, end):
        m = re.search(re.escape(start) + r"(.*?)" + re.escape(end), log, re.S)
        return m.group(1) if m else ""
    dump1 = re.findall(r"^ [0-9A-F]{8} .* 0001E0$|^ [0-9A-F]{8} .* 000000$", section(log1, "DUMP/BLOCK", "=IEND="), re.M)
    dump2 = re.findall(r"^ [0-9A-F]{8} .* 0001E0$|^ [0-9A-F]{8} .* 000000$", section(log2, "DUMP/BLOCK", "=DEND="), re.M)
    checks = [
        ("T1 boot and login", "Welcome to VAX/VMS" in log1),
        ("T1 DQA0 mounted, DQA1 present", re.search(r"DQA0:\s+on line mnt", log1) is not None and "DQA1:" in log1),
        ("T1 RB02 INITIALIZE/MOUNT", "RB02T        mounted on _DQA1:" in log1),
        ("T1 COPY and DIRECTORY (X.TMP 96 blocks)", re.search(r"X\.TMP;1\s+96", log1) is not None),
        ("T1 DUMP block 21 read", len(dump1) == 2),
        ("T2 RL11 MOUNT of the cartridge", "RB02T        mounted on _DLA0:" in log2),
        ("T2 DIRECTORY on the RL11 (X.TMP 96 blocks)", re.search(r"X\.TMP;1\s+96", log2) is not None),
        ("T2 block 21 equal to T1", len(dump2) == 2 and dump1 == dump2),
    ]
    mnt = section(log1, "DQA2: NOTHERE", "$ WRITE")
    print("rbtest v4: %s / %s, layout %s, extra: %s" % (a.vax730, a.vax750, a.layout, a.rbset or "-"))
    for name, ok in checks:
        print("  %-46s %s" % (name, "PASS" if ok else "FAIL"))
    print("  info: MOUNT on DQA2 without a cartridge -> %s" % " / ".join(l.strip() for l in mnt.strip().splitlines()) or "?")
    attach = [l for l in log1.splitlines() if l.startswith("%SIM-INFO: RB") or "RB0:" in l or "RB1:" in l]
    if attach:
        print("  info: attach messages: " + " / ".join(attach[:4]))
    return 0 if all(ok for _, ok in checks) else 1

if __name__ == "__main__":
    sys.exit(main())
