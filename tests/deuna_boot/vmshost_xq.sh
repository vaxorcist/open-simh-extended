#!/bin/bash
# open-simh-extended/tests/deuna_boot/vmshost_xq.sh  v3 (v3: HOST=microvax2 with DISK of type DTYPE (e.g. ra82: VMS V5.5) as the load host over its own DELQA (XQ, line/circuit QNA-0) instead of the vax780 with a DEUNA; v2: SVCDEV= service device for the node, default QNA, NONE for no SERVICE DEVICE)
#
# B13: net boot of a PDP-11/83 over a DEQNA, DELQA or DELQA-T (XQ, SIMH's
# BOOT XQ) from VMS V4.7 on a VAX-11/780 with a DEUNA (XU), the two
# joined by SIMH's UDP Ethernet transport (VAX udp:21403 <-> PDP-11
# udp:21404).  Reproduces Ulli's test of 2026-11-25 (DELQA: VMS logged
# "aborted service request, Line open error, Line communication error").
#   VAX:    boots a copy of DISK (VMS V4.7, node VAX4 1.4, SYSTEM/MANAGER),
#           copies SECQNA.SYS and TERQNA.SYS from a tape (TS11, MSA0) and
#           [006054]BRUSYS.SYS from Ulli's brusys.rl01 (RL01, ODS-1,
#           MOUNT/OVERRIDE=IDENTIFICATION DLA0:) into SYS$SYSTEM, defines
#           line/circuit UNA-0 (microvax2: QNA-0) with SERVICE ENABLED, starts DECnet and
#           defines node PDPNET (1.20): hardware address 08-00-2B-12-34-56,
#           service device QNA, CPU PDP11, SECQNA/TERQNA, LOAD FILE BRUSYS.SYS
#   PDP-11: 11/83, XQ of type TYPE, BOOT XQ.  The standalone BRU banner
#           ("RSX-11M/RSX-11M-PLUS STANDALONE COPY SYSTEM") means PASS.
# Needs here (not in the repository, DEC software): SECQNA.SYS, TERQNA.SYS
# (DECnet-11M V4.2 DECKIT [136,54]), brusys.rl01; ../dmv_regress/vmsrun.py.
#
# usage: TYPE=DEQNA|DELQA|DELQA-T [SVCDEV=QNA|NONE|...] [DEBUG=flags]
#        [HOST=vax780|microvax2] [DTYPE=ra81|ra82|...] vmshost_xq.sh BINDIR DISK
#        e.g. TYPE=DELQA ./vmshost_xq.sh ../../BIN diskA.vhd
BIN=$(readlink -f "$1"); DISK=$(readlink -f "$2"); TYPE=${TYPE:-DELQA}
cd "$(dirname "$0")" || exit 1
for f in SECQNA.SYS TERQNA.SYS brusys.rl01; do
    [ -f $f ] || { echo "B13 SKIP (missing $f)"; exit 0; }
done
SVCDEV=${SVCDEV:-QNA}; HOST=${HOST:-vax780}; DTYPE=${DTYPE:-ra81}
if [ $HOST = microvax2 ]; then LINE=QNA-0; else LINE=UNA-0; fi
R=run_xq_${HOST}_${TYPE}_$SVCDEV; rm -rf $R; mkdir -p $R
python3 -I mktap.py $R/qna.tap SECQNA.SYS TERQNA.SYS > /dev/null
cp --sparse=always "$DISK" $R/vax.vhd
cp brusys.rl01 $R/brusys.rl01
if [ $HOST = microvax2 ]; then NIC="set xq type=delqa
set xq mac=08:00:2b:00:0a:0a
attach xq udp:21403:127.0.0.1:21404
set debug $R/vax.dbg
set xq debug=${VDEBUG:-WARN}
expect \">>>\" send \"B DUA0\\r\"; continue
boot cpu"; else NIC="set xu enable
set xu type=deuna
set xu mac=08:00:2b:00:0a:0a
attach xu udp:21403:127.0.0.1:21404
set debug $R/vax.dbg
set xu debug=${VDEBUG:-WARN}
boot rq0"; fi
cat > $R/vax.ini <<EOT
; $R/vax.ini - generated by vmshost_xq.sh v3: the VMS load host ($HOST)
set cpu 16m
set cpu idle=vms
set rq0 $DTYPE
attach rq0 $R/vax.vhd
set ts enable
attach ts $R/qna.tap
set rl enable
attach rl0 $R/brusys.rl01
$NIC
EOT
cat > $R/vax.cmd <<EOT
MOUNT/FOREIGN/BLOCKSIZE=512/RECORDSIZE=512 MSA0:
COPY MSA0: SYS\$SYSTEM:SECQNA.SYS
COPY MSA0: SYS\$SYSTEM:TERQNA.SYS
DISMOUNT MSA0:
MOUNT/OVERRIDE=IDENTIFICATION DLA0:
COPY DLA0:[006054]BRUSYS.SYS SYS\$SYSTEM:BRUSYS.SYS
DISMOUNT DLA0:
DIRECTORY/SIZE=ALL SYS\$SYSTEM:SECQNA.SYS,TERQNA.SYS,BRUSYS.SYS
MC NCP PURGE KNOWN CIRCUITS ALL
MC NCP PURGE KNOWN LINES ALL
MC NCP DEFINE LINE $LINE STATE ON
MC NCP DEFINE CIRCUIT $LINE STATE ON SERVICE ENABLED
@SYS\$MANAGER:STARTNET
!WAIT 60
MC NCP SET NODE 1.20 NAME PDPNET
MC NCP SET NODE PDPNET SERVICE CIRCUIT $LINE HARDWARE ADDRESS 08-00-2B-12-34-56
MC NCP SET NODE PDPNET CPU PDP11
$( [ "$SVCDEV" != NONE ] && echo "MC NCP SET NODE PDPNET SERVICE DEVICE $SVCDEV")
MC NCP SET NODE PDPNET SECONDARY LOADER SYS\$SYSTEM:SECQNA.SYS
MC NCP SET NODE PDPNET TERTIARY LOADER SYS\$SYSTEM:TERQNA.SYS
MC NCP SET NODE PDPNET LOAD FILE SYS\$SYSTEM:BRUSYS.SYS
MC NCP SHOW CIRCUIT $LINE CHARACTERISTICS
MC NCP SHOW NODE PDPNET CHARACTERISTICS
WRITE SYS\$OUTPUT "NETBOOT","-READY"
!WAIT 150
MC NCP SHOW CIRCUIT $LINE COUNTERS
EOT
cat > $R/pdp.ini <<EOT
; $R/pdp.ini - generated by vmshost_xq.sh v1: the PDP-11/83 that boots
set cpu 11/83
set xq enable
set xq type=$TYPE
set xq mac=08:00:2b:12:34:56
attach xq udp:21404:127.0.0.1:21403
set debug $R/pdp.dbg
set xq debug=${DEBUG:-WARN}
boot xq
ex r0,r1,r2,r3,r4,r5,sp,pc
EOT
python3 -I ../dmv_regress/vmsrun.py $BIN/$HOST $R/vax.ini $R/vax.log $R/vax.cmd 1200 > $R/vax.out 2>&1 &
for i in $(seq 1 120); do                     # wait for the load host
    grep -aq "NETBOOT-READY" $R/vax.log 2>/dev/null && break
    sleep 5
done
grep -aq "NETBOOT-READY" $R/vax.log || { echo "B13 $HOST/$TYPE/$SVCDEV FAIL (the VMS load host did not get ready)"; wait; exit 1; }
SDL_AUDIODRIVER=dummy timeout 180 $BIN/pdp11 $R/pdp.ini < /dev/null 2>&1 | tr -d '\r' > $R/pdp.out
wait
tr -d '\r' < $R/vax.log | grep -a -E "event|Load, |File =|Circuit $LINE|Node =" | head -30
if grep -q "STANDALONE COPY SYSTEM" $R/pdp.out; then
    echo "B13 $HOST/$TYPE/$SVCDEV PASS"
else
    echo "B13 $HOST/$TYPE/$SVCDEV FAIL"; grep -v "^\s*$" $R/pdp.out | tail -8
fi
