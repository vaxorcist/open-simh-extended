#!/bin/bash
# open-simh-extended/tests/deuna_boot/vmshost.sh  v5 (v5: status: the VMS load host sends SECUNA and TERUNA through SIMH's DEUNA and TERUNA asks for the system, but VMS treats the LOAD FILE as an RSX-11S system image with downline load parameters inside (set by DECnet-RSX's VNP) and loaded zeros from 0 to 173777 for NETTEST.SYS: B9 needs a real RSX-11S system image; v4: NETTEST.SYS with a task label in block 0, loaded from 0 (mknettest.py v4), HALT at PC 000134; v3: NETTEST.SYS 4 blocks (mknettest.py v3); v2: NETTEST.SYS as a memory image from 0 (mknettest.py v2); memory dump after the halt)
#
# B9: net boot of a PDP-11 from a real load host: VMS V4.7 on a VAX-11/780
# with a DEUNA (XU), joined to the PDP-11's DEUNA by SIMH's UDP Ethernet
# transport (VAX udp:21403 <-> PDP-11 udp:21404).
#   VAX:    boots a copy of DISK (VMS V4.7, node VAX4 1.4, SYSTEM/MANAGER),
#           copies SECUNA.SYS, TERUNA.SYS and NETTEST.SYS from a tape
#           (TS11, MSA0) into SYS$SYSTEM, defines line/circuit UNA-0 with
#           SERVICE ENABLED, starts DECnet and defines node PDPNET (1.20)
#           with the PDP-11's hardware address 08-00-2B-12-34-56, service
#           device UNA, CPU PDP11, the two loaders and LOAD FILE NETTEST.SYS
#   PDP-11: 11/34 with the 23-248F1 console and the 'XE' boot ROMs; the
#           console's XE0 gives BOOT; the boot engine asks for the
#           secondary (VMS sends SECUNA), does SECUNA's work (VMS sends
#           TERUNA); TERUNA asks for the system (VMS sends NETTEST.SYS) and
#           starts it: HELLO FROM THE VMS LOAD HOST, HALT at PC 000134.
# Needs here: m9312_248F1.bin, m9312_xe.bin, SECUNA.SYS, TERUNA.SYS (not in
# the repository), ../dmv_regress/vmsrun.py; makes NETTEST.SYS and the tape.
#
# usage: vmshost.sh BINDIR DISK     e.g. vmshost.sh ../../BIN diskA.vhd
BIN=$(readlink -f "$1"); DISK=$(readlink -f "$2")
cd "$(dirname "$0")" || exit 1
for f in m9312_248F1.bin m9312_xe.bin SECUNA.SYS TERUNA.SYS; do
    [ -f $f ] || { echo "B9 SKIP (missing $f)"; exit 0; }
done
R=run_b9; rm -rf $R; mkdir -p $R
python3 -I mknettest.py NETTEST.SYS "HELLO FROM THE VMS LOAD HOST" > /dev/null
python3 -I mktap.py $R/netboot.tap SECUNA.SYS TERUNA.SYS NETTEST.SYS > /dev/null
cp --sparse=always "$DISK" $R/vax.vhd
cat > $R/vax.ini <<EOT
; $R/vax.ini - generated by vmshost.sh v4: the VMS V4.7 load host
set cpu 16m
set cpu idle=vms
set rq0 ra81
attach rq0 $R/vax.vhd
set ts enable
attach ts $R/netboot.tap
set xu enable
set xu type=deuna
set xu mac=08:00:2b:00:0a:0a
attach xu udp:21403:127.0.0.1:21404
boot rq0
EOT
cat > $R/vax.cmd <<'EOT'
MOUNT/FOREIGN/BLOCKSIZE=512/RECORDSIZE=512 MSA0:
COPY MSA0: SYS$SYSTEM:SECUNA.SYS
COPY MSA0: SYS$SYSTEM:TERUNA.SYS
COPY MSA0: SYS$SYSTEM:NETTEST.SYS
DISMOUNT MSA0:
DIRECTORY/SIZE=ALL SYS$SYSTEM:SECUNA.SYS,TERUNA.SYS,NETTEST.SYS
MC NCP PURGE KNOWN CIRCUITS ALL
MC NCP PURGE KNOWN LINES ALL
MC NCP DEFINE LINE UNA-0 STATE ON
MC NCP DEFINE CIRCUIT UNA-0 STATE ON SERVICE ENABLED
@SYS$MANAGER:STARTNET
!WAIT 60
MC NCP SET NODE 1.20 NAME PDPNET
MC NCP SET NODE PDPNET SERVICE CIRCUIT UNA-0 HARDWARE ADDRESS 08-00-2B-12-34-56
MC NCP SET NODE PDPNET SERVICE DEVICE UNA CPU PDP11
MC NCP SET NODE PDPNET SECONDARY LOADER SYS$SYSTEM:SECUNA.SYS
MC NCP SET NODE PDPNET TERTIARY LOADER SYS$SYSTEM:TERUNA.SYS
MC NCP SET NODE PDPNET LOAD FILE SYS$SYSTEM:NETTEST.SYS
MC NCP SHOW CIRCUIT UNA-0 CHARACTERISTICS
MC NCP SHOW NODE PDPNET CHARACTERISTICS
WRITE SYS$OUTPUT "NETBOOT","-READY"
!WAIT 150
MC NCP SHOW CIRCUIT UNA-0 COUNTERS
EOT
cat > $R/pdp.ini <<EOT
; $R/pdp.ini - generated by vmshost.sh v4: the PDP-11 that boots
set cpu 11/34
set cpu 64k
set xu enable
set xu type=deuna
set xu mac=08:00:2b:12:34:56
attach xu udp:21404:127.0.0.1:21403
set debug $R/pdp.dbg
set xu debug=BOOT
set rom0 address=17765000
attach rom0 m9312_248F1.bin
set rom1 address=17773000
attach rom1 m9312_xe.bin
expect "@" send "XE0\r"; continue
go 165020
ex r0,r1,r2,r3,r4,r5,sp,pc
ex 0/100
ex 2000/20
EOT
python3 -I ../dmv_regress/vmsrun.py $BIN/vax780 $R/vax.ini $R/vax.log $R/vax.cmd 1200 > $R/vax.out 2>&1 &
for i in $(seq 1 120); do                     # wait for the load host
    grep -aq "NETBOOT-READY" $R/vax.log 2>/dev/null && break
    sleep 5
done
grep -aq "NETBOOT-READY" $R/vax.log || { echo "B9 FAIL (the VMS load host did not get ready)"; wait; exit 1; }
SDL_AUDIODRIVER=dummy timeout 240 $BIN/pdp11 $R/pdp.ini < /dev/null 2>&1 | tr -d '\r' > $R/pdp.out
wait
if grep -q "HELLO FROM THE VMS LOAD HOST" $R/pdp.out && grep -q "HALT instruction, PC: 000134" $R/pdp.out; then
    echo "B9 PASS"
else
    echo "B9 FAIL"; tail -5 $R/pdp.out
fi
