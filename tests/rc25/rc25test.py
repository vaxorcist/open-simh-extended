# RC25 regression and realism tests with VMS V3.5 on the VAX-11/730:
# the system disk is the fixed platter (RQ1, RCF25, DUA1), the cartridge
# (RQ0, RC25, DUA0) starts blank.
#
#   N1 normal mode:  boot DUA1, SHOW DEVICE DU, INITIALIZE/MOUNT/COPY/
#                    DIRECTORY/DISMOUNT on DUA0; Run button OFFLINE/ONLINE
#                    under the running system (both platters stop: mount
#                    verification of the system disk), DISMOUNT/UNLOAD
#   R1 realism mode: SET RQ1 ONLINE refused without a cartridge; with the
#                    cartridge ONLINE via the fixed unit; boot, the same
#                    DCL work; DISMOUNT/UNLOAD DUA0 while DUA1 is online
#                    must not stop the drive; Run button OFFLINE/ONLINE
#                    under the running system; seek sounds counted
#
# Usage: python3 -I rc25test.py <vax730> <VMS V3.5 RCF25 image> <work dir> [N1|R1 ...]
# The image is copied; the original is not changed.
import sys, os, subprocess, shutil, time

def step(cmd, tag):
    """DCL command, then a marker line; the script stops at the marker."""
    return ('send after=1000000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"\n'
            'expect "=%sEND="\ncontinue\n' % (cmd.replace('"', '\\"'), tag, tag))

LOGIN = ('expect "job terminated" send after=3000000,"\\r"; continue\n'
         'expect "Username:" send "SYSTEM\\r"; continue\n'
         'expect "Password:" send "MANAGER\\r"; continue\n'
         'expect "Welcome"\n')

def dcl_work(tag):
    s = ""
    s += step("SET TERMINAL/WIDTH=132", tag + "A")
    s += step("SHOW DEVICE DU", tag + "B")
    s += step("INITIALIZE DUA0: RC25T", tag + "C")
    s += step("MOUNT DUA0: RC25T", tag + "D")
    s += step("COPY SYS$SYSTEM:SYSUAF.DAT DUA0:[000000]A.DAT", tag + "E")
    s += step("COPY SYS$SYSTEM:SYSUAF.DAT DUA0:[000000]B.DAT", tag + "F")
    s += step("DIRECTORY/SIZE DUA0:[000000]", tag + "G")
    s += step("DISMOUNT/NOUNLOAD DUA0:", tag + "H")             # (DISMOUNT unloads by default)
    return s

def run(sim, ini, log, limit):
    t = time.time()
    with open(log, "wb") as f:
        subprocess.run([sim, ini], stdout=f, stderr=subprocess.STDOUT, timeout=limit,
                       env=dict(os.environ, SDL_AUDIODRIVER="dummy"))
    txt = open(log, "rb").read().replace(b"\0", b"").decode("latin-1")
    return txt, time.time() - t

def main():
    sim, image, work = sys.argv[1], sys.argv[2], sys.argv[3]
    which = sys.argv[4:] or ["N1", "R1"]
    os.makedirs(work, exist_ok=True)
    w = lambda f: os.path.join(work, f)
    res = []
    if "N1" in which:
        shutil.copyfile(image, w("n1.rcf25")); os.chmod(w("n1.rcf25"), 0o644)
        for f in ("n1.rc25",):
            if os.path.exists(w(f)): os.remove(w(f))
        s = "; N1 (generated by rc25test.py v2)\nset cpu 4m\nset rq0 rc25\nset rq1 rcf25\n"
        s += "attach rq1 n1.rcf25\nattach -n rq0 n1.rc25\nset runlimit 900 seconds\n" + LOGIN + "boot rq1\n"
        s += dcl_work("N")
        s += "echo ==== N1: Run button OFFLINE under the running system\nset rq0 offline\nshow rq1 spindle\n"
        s += 'send after=1000000,"DIRECTORY SYS$SYSTEM:SYSUAF.DAT\\r"\nexpect "is offline"\ncontinue\n'
        s += "echo ==== N1: Run button ONLINE\nset rq1 online\n"
        s += 'expect "has completed mount verification"\ncontinue\n'
        s += step("SHOW DEVICE DU", "NI")
        s += step("MOUNT DUA0: RC25T", "NJ")
        s += step("DISMOUNT/UNLOAD DUA0:", "NK")
        s += "echo ==== N1: after DISMOUNT/UNLOAD DUA0\nshow rq0\nshow rq0 spindle\nshow rq1 spindle\n"
        s += step("SHOW DEVICE DU", "NL")
        s += "exit\n"
        open(w("n1.ini"), "w").write(s)

        os.chdir(work); txt, dt = run(sim, "n1.ini", "n1.log", 1000)
        res += [("N1 boot and login", "Welcome" in txt),
                ("N1 INITIALIZE/MOUNT/COPY/DIRECTORY", "B.DAT" in txt and "%INIT-F" not in txt and "%MOUNT-F" not in txt),
                ("N1 OFFLINE: mount verification of DUA1", "DUA1: is offline" in txt),
                ("N1 ONLINE: mount verification completed", "has completed mount verification" in txt),
                ("N1 DISMOUNT/UNLOAD DUA0 (normal mode: cartridge unloaded)", "not attached" in txt.split("after DISMOUNT/UNLOAD")[-1][:400])]
        print("N1: %.0f s" % dt)
    if "R1" in which:
        shutil.copyfile(image, w("r1.rcf25")); os.chmod(w("r1.rcf25"), 0o644)
        if os.path.exists(w("r1.rc25")): os.remove(w("r1.rc25"))
        s = "; R1 (generated by rc25test.py v2)\nset sound enabled\nset cpu 4m\nset rq0 rc25\nset rq1 rcf25\n"
        s += "deposit rq SPINUPRC25 5000\ndeposit rq SPINDOWNRC25 3000\n"
        s += "attach rq1 r1.rcf25\necho ==== R1: ONLINE without a cartridge\nset rq1 online\nshow rq1 spindle\n"
        s += "attach -n rq0 r1.rc25\nshow rq0 spindle\necho ==== R1: ONLINE via the fixed unit\nset rq1 online\n"
        s += "set debug r1.dbg\nset rq debug=trace\nset runlimit 1500 seconds\n" + LOGIN + "boot rq1\n"
        s += "echo ==== R1: logged in\n"
        s += dcl_work("R")
        s += step("MOUNT DUA0: RC25T", "RI")
        s += step("DISMOUNT/UNLOAD DUA0:", "RJ")
        s += "echo ==== R1: after DISMOUNT/UNLOAD DUA0 (DUA1 online: no spin-down)\nshow rq0 spindle\nshow rq1 spindle\n"
        s += step("SHOW DEVICE DU", "RK")
        s += "echo ==== R1: Run button OFFLINE under the running system\nset -n rq0 offline\nshow rq1 spindle\n"
        s += 'send after=1000000,"DIRECTORY SYS$SYSTEM:SYSUAF.DAT\\r"\nexpect "is offline"\ncontinue\n'
        s += "echo ==== R1: Run button ONLINE (waits for the spin-up)\nset rq0 online\n"
        s += 'expect "has completed mount verification"\ncontinue\n'
        s += step("SHOW DEVICE DU", "RL")
        s += "set rq nodebug\nexit\n"
        open(w("r1.ini"), "w").write(s)
        os.chdir(work); txt, dt = run(sim, "r1.ini", "r1.log", 1600)
        dbg = open("r1.dbg", "rb").read().decode("latin-1") if os.path.exists("r1.dbg") else ""
        tail = txt.split("after DISMOUNT/UNLOAD DUA0")[-1][:300]
        res += [("R1 ONLINE refused without a cartridge", "the RC25 does not start without one" in txt),
                ("R1 boot and login", "Welcome" in txt and "logged in" in txt),
                ("R1 INITIALIZE/MOUNT/COPY/DIRECTORY", "B.DAT" in txt and "%INIT-F" not in txt and "%MOUNT-F" not in txt),
                ("R1 DISMOUNT/UNLOAD DUA0 keeps the drive running", "online" in tail and "spinning down" not in tail),
                ("R1 OFFLINE: mount verification of DUA1", "DUA1: is offline" in txt),
                ("R1 ONLINE: mount verification completed", "has completed mount verification" in txt)]
        for c in ("short", "medium", "long"):
            print("R1 seek sounds %s: DUA0 %d, DUA1 %d" % (c, dbg.count("RQ0: RC25 seek sound " + c), dbg.count("RQ1: RC25 seek sound " + c)))
        print("R1: %.0f s" % dt)
    for name, ok in res:
        print("%-62s %s" % (name, "ok" if ok else "FAILED"))

if __name__ == "__main__":
    main()
