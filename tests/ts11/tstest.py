# open-simh-extended/tests/ts11/tstest.py  v2
#
# v2 (2026-11-10): realism runs press the RA81 RUN/STOP button (SET RQ0
# ONLINE) after ATTACH, the MicroVAX II run uses a KDA50 (SDI rules).
#
# TS11/TSV05 tests with VMS V4.7 (Ulli's image VMS047-1.R81, RA81, VHD;
# SYSTEM/MANAGER) for the sound realism mode of the TS device:
#
#   N1 normal mode, VAX-11/750 (TS11):  ATTACH loads the tape at once;
#        sizes of the test files; INITIALIZE MSA0:, BACKUP save set,
#        BACKUP/LIST, DISMOUNT (unloads: detaches, as before)
#   R1 realism mode, VAX-11/750 (TS11): ATTACH only mounts the reel;
#        SET TS ONLINE (load); BACKUP save set and BACKUP/LIST with the
#        guest's clock before/after (realistic tape time); DISMOUNT
#        unloads (rewind + unload, the file stays attached, off-line);
#        SET TS ONLINE loads it again, BACKUP/LIST
#   E1 realism mode, VAX-11/750: REEL=600 and a bigger save set (2 KB
#        blocks): physical EOT, BACKUP asks for the next volume
#   Q1 realism mode, MicroVAX II (TSV05): as R1 without the EOT part,
#        streaming at 25 in/s
#   P1 realism mode, VAX-11/750: a guest rewind goes on in wall time at
#        the sim> prompt (SHOW TS TRANSPORT, SLEEP, SHOW again), RUN
#        resumes it; SET -N TS UNLOAD returns at once
#
# Usage: python3 -I tstest.py <BIN directory> <VMS047-1.R81> <work dir> [N1|R1|Q1 ...]
# The image is copied; the original is not changed.  The simulator output
# goes to <work dir>/<test>.log; the audio (SDL disk driver) to
# <work dir>/<test>.raw (float mono 44100 Hz) if AUDIO=1 is set.
import sys, os, subprocess, shutil, time

def step(cmd, tag):
    """DCL command, then a marker line; the script stops at the marker."""
    return ('send after=500000,"%s\\rWRITE SYS$OUTPUT \\"=%s\\",\\"END=\\"\\r"\n'
            'expect "=%sEND="\ncontinue\n' % (cmd.replace('"', '\\"'), tag, tag))

def clock(tag):
    return step('WRITE SYS$OUTPUT "CLOCK ' + tag + ' ",F$TIME()', "K" + tag)

LOGIN = ('expect "job terminated" send after=2000000,"\\r"; continue\n'
         'expect "Username:" send "SYSTEM\\r"; continue\n'
         'expect "Password:" send "MANAGER\\r"; continue\n'
         'expect "Welcome"\n')

SMALL = "SYS$HELP:*.HLB"            # about 3 MB
BIG = "SYS$SYSTEM:*.EXE"            # more than a 600 ft reel holds

def save_list(tag, files):
    s = ""
    s += step("SET TERMINAL/WIDTH=132", tag + "A")
    s += step("INITIALIZE MSA0: TSTEST", tag + "B")
    s += step("MOUNT/FOREIGN MSA0:", tag + "C")
    s += clock(tag + "1")
    s += step("BACKUP/NOLOG " + files + " MSA0:T.BCK/SAVE_SET/REWIND/LABEL=TSTEST", tag + "D")
    s += clock(tag + "2")
    s += "echo ==== %s: after BACKUP\nshow ts transport\n" % tag
    s += step("BACKUP/LIST=SYS$LOGIN:L.LIS MSA0:T.BCK/SAVE_SET/REWIND", tag + "E")
    s += clock(tag + "3")
    s += step("SEARCH SYS$LOGIN:L.LIS \"Total of\"", tag + "F")
    return s

def run(sim, ini, log, limit, audio):
    t = time.time()
    env = dict(os.environ)
    if audio:
        env["SDL_AUDIODRIVER"] = "disk"
        env["SDL_DISKAUDIOFILE"] = audio
    else:
        env["SDL_AUDIODRIVER"] = "dummy"
    with open(log, "wb") as f:
        subprocess.run([sim, ini], stdout=f, stderr=subprocess.STDOUT, timeout=limit,
                       env=env, stdin=subprocess.DEVNULL)
    txt = open(log, "rb").read().replace(b"\0", b"").decode("latin-1")
    return txt, time.time() - t

def run_p1(sim, image, w, res):
    disk = w("p1.vhd")
    shutil.copyfile(image, disk); os.chmod(disk, 0o644)
    if os.path.exists(w("p1.tap")): os.remove(w("p1.tap"))
    s = "; P1 (generated by tstest.py v2)\nset sound enabled\nset cpu 8m\nset rq0 ra81\n"
    s += "attach rq0 %s\nset rq0 online\nattach -n ts %s\nset ts online\n" % (disk, w("p1.tap"))
    s += "set runlimit 3600 seconds\n" + LOGIN + "boot rq0\n"
    s += step("INITIALIZE MSA0: TSTEST", "PA") + step("MOUNT/FOREIGN MSA0:", "PB")
    s += step("BACKUP/NOLOG " + SMALL + " MSA0:T.BCK/SAVE_SET/REWIND/LABEL=TSTEST", "PC")
    s += "echo ==== P1: after BACKUP\nshow ts transport\n"
    s += clock("P1")
    s += 'send after=200000,"DISMOUNT/NOUNLOAD MSA0:\\r"\nexpect "NOUNLOAD MSA0:"\ncontinue\n'
    s += "echo ==== P1: at the prompt while the guest rewinds\nstep 600000\nshow ts transport\nsleep 5\nshow ts transport\n"
    s += 'echo ==== P1: 5 s later, now continue\nexpect "$ "\ncontinue\n'
    s += clock("P2")
    s += "echo ==== P1: after DISMOUNT\nshow ts transport\nset ts offline\nset -n ts unload\nshow ts transport\n"
    s += "sleep 3\nshow ts transport\nset ts unload\nshow ts transport\nexit\n"
    open(w("p1.ini"), "w").write(s)
    txt, secs = run(sim, w("p1.ini"), w("p1.log"), 4000, None)
    res.append(("P1", secs, txt))
    print("P1: %.0f s wall" % secs)

def run_e1(sim, image, w, res):
    disk = w("e1.vhd")
    shutil.copyfile(image, disk); os.chmod(disk, 0o644)
    if os.path.exists(w("e1.tap")): os.remove(w("e1.tap"))
    s = "; E1 (generated by tstest.py v2)\nset sound enabled\nset cpu 8m\nset rq0 ra81\n"
    s += "attach rq0 %s\nset rq0 online\nset ts reel=600\nattach -n ts %s\nset ts online\nshow ts transport\n" % (disk, w("e1.tap"))
    s += "set runlimit 3600 seconds\n" + LOGIN + "boot rq0\n"
    s += step("INITIALIZE MSA0: TSBIG", "EK") + step("MOUNT/FOREIGN MSA0:", "EL")
    s += clock("E1")
    s += ('send after=500000,"BACKUP/NOLOG/BLOCK_SIZE=2048 %s MSA0:B.BCK/SAVE_SET/REWIND/LABEL=TSBIG\\r"\n'
          'expect "mount volume 2"\ncontinue\n' % BIG)
    s += "echo ==== E1: BACKUP at the end of the reel\nshow ts transport\n"
    s += 'send after=1000000,"\\031"\n'                   # Ctrl/Y ends BACKUP
    s += clock("E2")
    s += "show ts transport\nexit\n"
    open(w("e1.ini"), "w").write(s)
    txt, secs = run(sim, w("e1.ini"), w("e1.log"), 4000, None)
    res.append(("E1", secs, txt))
    print("E1: %.0f s wall" % secs)

def main():
    bindir, image, work = sys.argv[1], sys.argv[2], sys.argv[3]
    which = sys.argv[4:] or ["N1", "R1", "Q1"]
    os.makedirs(work, exist_ok=True)
    w = lambda f: os.path.join(work, f)
    audio_on = os.environ.get("AUDIO") == "1"
    res = []
    for test in which:
        sim = os.path.join(bindir, "microvax2" if test == "Q1" else "vax750")
        if test == "P1":
            run_p1(sim, image, w, res)
            continue
        if test == "E1":
            run_e1(sim, image, w, res)
            continue
        disk = w(test.lower() + ".vhd")
        shutil.copyfile(image, disk); os.chmod(disk, 0o644)
        for f in (test.lower() + ".tap", test.lower() + "b.tap"):
            if os.path.exists(w(f)): os.remove(w(f))
        s = "; %s (generated by tstest.py v2)\n" % test
        if test in ("R1", "Q1"):                # before any ATTACH
            s += "set sound enabled\nshow sound\n"
        if test == "Q1":                         # MicroVAX II: 16 MB, console ROM
            s += "set cpu 16m\nset rq kda50\nset rq0 ra81\nattach rq0 %s\n" % disk
        else:
            s += "set cpu 8m\nset rq0 ra81\nattach rq0 %s\n" % disk
        if test in ("R1", "Q1"):                 # realism: the RA81 RUN/STOP button
            s += "set rq0 online\n"
        s += "attach -n ts %s\n" % w(test.lower() + ".tap")
        s += "echo ==== %s: after ATTACH\nshow ts transport\n" % test
        if test in ("R1", "Q1"):
            s += "set ts online\nshow ts transport\n"
        if test == "Q1":
            s += ('set runlimit 3600 seconds\nexpect ">>>" send "B DUA0\\r"; continue\n'
                  'expect "HH:MM)" send "7-NOV-2026 23:30\\r"; continue\n') + LOGIN + "boot cpu\n"
        else:
            s += "set runlimit 3600 seconds\n" + LOGIN + "boot rq0\n"
        if test == "N1":
            s += step("DIRECTORY/SIZE/GRAND " + SMALL, "NS")
            s += step("DIRECTORY/SIZE/GRAND " + BIG, "NT")
        s += save_list(test[0], SMALL)
        s += step("DISMOUNT MSA0:", test[0] + "G")
        s += "echo ==== %s: after DISMOUNT (unloads)\nshow ts\nshow ts transport\n" % test
        if test in ("R1", "Q1"):
            s += "echo ==== %s: SET TS ONLINE loads the tape again\nset ts online\nshow ts transport\n" % test
            s += step("MOUNT/FOREIGN MSA0:", test[0] + "H")
            s += step("BACKUP/LIST MSA0:T.BCK/SAVE_SET/REWIND", test[0] + "I")
            s += step("DISMOUNT/NOUNLOAD MSA0:", test[0] + "J")
            s += "show ts transport\n"
        s += "exit\n"
        open(w(test.lower() + ".ini"), "w").write(s)
        audio = w(test.lower() + ".raw") if audio_on else None
        txt, secs = run(sim, w(test.lower() + ".ini"), w(test.lower() + ".log"), 4000, audio)
        res.append((test, secs, txt))
        print("%s: %.0f s wall" % (test, secs))
    for test, secs, txt in res:
        print("==== %s" % test)
        for line in txt.splitlines():
            l = line.strip()
            if (l.startswith("CLOCK") or "transport:" in l or l.startswith("====") or
                "Total of" in l or "%BACKUP" in l or "%MOUNT" in l or "%SYSTEM" in l or
                "-F-" in l or "-E-" in l or "MSA0" in l and ("not" in l or "offline" in l.lower())):
                print("   " + l)

main()
